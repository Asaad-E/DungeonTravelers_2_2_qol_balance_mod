"""
The engine against the program, item by item: docs/generated/ENGINE_CONFORMITY.md, generated from
data_tables/engine_conformity.json (the 99 items of the engine audit of 2026-10-18, plan docs/ENGINE_AUDIT.md, with the
verdict each has after the fixes that followed it).

    python tools/engine_conformity.py           writes the document; exit 1 when a check fails
    python tools/engine_conformity.py --check   only the checks

For every item: the verdict is a word of the list VERDICTS (no MISMATCH or PARTIAL may remain), a FIXED item names the
commit of its fix, a MODEL-LIMIT item says what the engine leaves out, every address of the program falls in a section
of the executable, and every place of the engine ('File.cs:Method') is a file of engine_cs/src that still defines that
method. Reads the program; plays no battle.
"""
import json
import os
import re
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from exe_reader import Exe          # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE = os.path.join(ROOT, 'data_tables', 'engine_conformity.json')
OUTPUT = os.path.join(ROOT, 'docs', 'generated', 'ENGINE_CONFORMITY.md')
SRC = os.path.join(ROOT, 'engine_cs', 'src')
VERDICTS = ('MATCH', 'FIXED', 'MODEL-LIMIT', 'N/A')


def sources():
    found = {}
    for folder, dirs, files in os.walk(SRC):
        dirs[:] = [d for d in dirs if d not in ('bin', 'obj')]
        for name in files:
            if name.endswith('.cs'):
                found.setdefault(name, []).append(os.path.join(folder, name))
    return found


def checks(items):
    exe, files, failed = Exe(), sources(), []
    texts = {}
    for it in items:
        pid = it['id']
        if it['verdict'] not in VERDICTS:
            failed.append(f'{pid}: verdict {it["verdict"]}')
        if it['verdict'] == 'FIXED' and not re.fullmatch(r'[0-9a-f]{7,40}', it.get('fixed_in', '')):
            failed.append(f'{pid}: FIXED without the commit of its fix')
        if it['verdict'] in ('FIXED', 'MODEL-LIMIT') and not it.get('note'):
            failed.append(f'{pid}: {it["verdict"]} without a note')
        for a in it['program']:
            if not any(start <= int(a, 16) < start + max(vsize, rsize) for _, start, vsize, _, rsize in exe.sections):
                failed.append(f'{pid}: address {a} is in no section of the program')
        for place in it['engine']:
            name, _, method = place.partition(':')
            if name not in files:
                failed.append(f'{pid}: no file {name} in engine_cs/src')
                continue
            if method:
                if name not in texts:
                    texts[name] = '\n'.join(open(p, encoding='utf-8').read() for p in files[name])
                if not re.search(r'\b' + re.escape(method) + r'\s*(<[^>]*>)?\(', texts[name]):
                    failed.append(f'{pid}: {name} defines no {method}')
    return failed


def cell(text):
    return str(text).replace('|', '\\|').replace('\n', ' ')


def write(data):
    items = data['items']
    count = Counter(it['verdict'] for it in items)
    phases = {}
    for it in items:
        phases.setdefault(it['id'].split('.')[0], []).append(it)
    out = ['# Engine conformity', '',
           '<!-- generated by tools/engine_conformity.py from data_tables/engine_conformity.json; do not edit -->', '',
           f'{data["source"]}. Every mechanic the engine plays was read in the program and held against the engine; '
           'the command of an item repeats the reading (`tools/exe_dis.py`). The method of the audit, its phases and '
           'its rules are in docs/ENGINE_AUDIT.md.', '',
           '| Verdict | Items | Meaning |', '|---|---|---|',
           f'| MATCH | {count["MATCH"]} | the engine does what the program does |',
           f'| FIXED | {count["FIXED"]} | the audit found a difference; the engine was corrected (commit named) |',
           f'| MODEL-LIMIT | {count["MODEL-LIMIT"]} | the engine leaves out a detail on purpose; the note says which, and where it can matter |',
           f'| N/A | {count["N/A"]} | not a mechanic of a battle |',
           f'| Total | {len(items)} | |', '']
    for phase, rows in phases.items():
        out += [f'## Phase {phase[1:]}', '', '| Item | Mechanic | Program | Engine | Verdict | Note |', '|---|---|---|---|---|---|']
        for it in rows:
            verdict = it['verdict'] + (f' ({it["fixed_in"]})' if it.get('fixed_in') else '')
            out.append(f'| {it["id"]} | {cell(it["mechanic"])} | {", ".join(it["program"][:5])} | '
                       f'{", ".join(it["engine"][:4])} | {verdict} | {cell(it.get("note", ""))} |')
        out.append('')
    with open(OUTPUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))


def main():
    data = json.load(open(TABLE, encoding='utf-8'))
    failed = checks(data['items'])
    if '--check' not in sys.argv:
        write(data)
    count = Counter(it['verdict'] for it in data['items'])
    print(f'{len(data["items"])} items: ' + ', '.join(f'{k} {count[k]}' for k in VERDICTS) + f'; {len(failed)} failing')
    for line in failed:
        print('  ' + line)
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main())
