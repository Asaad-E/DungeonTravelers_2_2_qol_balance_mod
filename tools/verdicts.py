"""
The checklist of phase 2: the verdict of every row of the sheet Criticisms, by theme. Generated:
docs/generated/VERDICTS.md.

    python tools/verdicts.py

A row ends closed, not a problem or out of the balance (BALANCE_PLAN.md section 8); open is a row with no verdict yet.
Theme and state are the columns Theme and Status of data_tables/balance_criteria.xlsx. A theme is done when it has no
open row; the mod goes to the user when no row is open and the final pass holds.
"""
import os
import sys
from collections import Counter, OrderedDict

import openpyxl

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CRITERIA = os.path.join(BASE_DIR, 'data_tables', 'balance_criteria.xlsx')
OUTPUT = os.path.join(BASE_DIR, 'docs', 'generated', 'VERDICTS.md')
STATES = ('open', 'closed', 'not a problem', 'out of the balance')


def criticisms(path=CRITERIA):
    it = openpyxl.load_workbook(path, read_only=True)['Criticisms'].iter_rows(values_only=True)
    header = next(it)
    return [dict(zip(header, r)) for r in it if r and r[0] is not None]


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    rows = criticisms()
    unknown = sorted({str(r['Status']) for r in rows} - set(STATES))
    no_theme = [r['ID'] for r in rows if not r.get('Theme')]
    themes = OrderedDict()
    for r in sorted(rows, key=lambda r: (str(r['Theme']).startswith('Out'), str(r['Theme']))):
        themes.setdefault(r['Theme'], []).append(r)
    total = Counter(r['Status'] for r in rows)
    out = ['# Phase 2 checklist: verdicts of the register (generated)', '',
           'Generated by `tools/verdicts.py` from the columns `Theme` and `Status` of the sheet `Criticisms` of '
           '`data_tables/balance_criteria.xlsx`. Do not edit: run the tool again.', '',
           f'Rows: {len(rows)}. ' + ', '.join(f'{s}: {total.get(s, 0)}' for s in STATES) + '. '
           f'Open rows with a verdict and its figure written (column Verdict), waiting for the decision of the user: '
           f'{sum(1 for r in rows if r["Status"] == "open" and r.get("Verdict"))}.', '']
    if unknown or no_theme:
        out += [f'States not in the list: {", ".join(unknown) or "none"}. Rows with no theme: '
                f'{", ".join(no_theme) or "none"}.', '']
    out += ['| Theme | Rows | ' + ' | '.join(s.capitalize() for s in STATES) + ' | Verdict written |',
            '|---|---|' + '---|' * (len(STATES) + 1)]
    for theme, group in themes.items():
        count = Counter(r['Status'] for r in group)
        out.append(f'| {theme} | {len(group)} | ' + ' | '.join(str(count.get(s, 0)) for s in STATES) +
                   f' | {sum(1 for r in group if r.get("Verdict"))} |')
    for theme, group in themes.items():
        out += ['', f'## {theme}', '', '| Row | Subject | State | Verdict | Why |', '|---|---|---|---|---|']
        out += [f'| {r["ID"]} | {r["Subject"]} | {r["Status"]} | {r.get("Verdict") or ""} | '
                f'{(r.get("Why") or "").replace("|", "/")} |' for r in group]
    with open(OUTPUT, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(out) + '\n')
    print(f'{len(rows)} rows: ' + ', '.join(f'{s} {total.get(s, 0)}' for s in STATES) +
          f'; verdicts written {sum(1 for r in rows if r.get("Verdict"))}; written {OUTPUT}')


if __name__ == '__main__':
    main()
