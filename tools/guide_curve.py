"""
The story bosses against what the guide says of them. Generated: docs/generated/GUIDE_CURVE.md.

    python tools/guide_curve.py run k/n      plays the k-th of n slices of the sheet, one process each
    python tools/guide_curve.py report       joins the slices into the checklist

The sheet GuideDifficulty of data_tables/sim_setup.xlsx gives each story checkpoint the class the GameFAQs guide
gives its boss (easy, normal, hard). The reference party at the reference level of the checkpoint plays it on the
vanilla data (sim/measures.py play_checkpoint, check_runs runs); a boss whose win share falls below the floor of its
class (Settings guide_<class>_min_won) is a row to read: a gap of the model or a boss harder than the guide says. Its
reading goes in the sheet AuditReadings, under the ID 'curve <checkpoint>'. The check is done when every row is
within its floor or read.
"""
import json
import os
import sys

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, BASE_DIR)
OUT_DIR = os.path.join(BASE_DIR, 'docs', 'generated', 'guide_curve')
REPORT = os.path.join(BASE_DIR, 'docs', 'generated', 'GUIDE_CURVE.md')

from sim import measures                                # noqa: E402
from sim import setup as setup_mod                      # noqa: E402
from sim.data import game_data                          # noqa: E402


def sheet(setup):
    import openpyxl
    wb = openpyxl.load_workbook(setup_mod.SETUP, read_only=True)
    rows = list(wb['GuideDifficulty'].iter_rows(values_only=True))
    return [dict(zip(rows[0], r)) for r in rows[1:] if r[0]]


def run(part='1/1'):
    k, n = (int(x) for x in part.split('/'))
    data, setup = game_data(), setup_mod.load()
    rows = sheet(setup)
    mine = rows[(k - 1) * len(rows) // n: k * len(rows) // n]
    runs = int(setup.settings['check_runs'])
    out = []
    for r in mine:
        level, res = measures.play_checkpoint(data, setup, r['Checkpoint'], runs)
        out.append({'id': r['Checkpoint'], 'level': level, 'won': res['won'], 'time': res.get('time'),
                    'lowest_hp': res['lowest_hp']})
        print(r['Checkpoint'], level, f"won {res['won']:.0%}", flush=True)
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, f'part_{k}.json'), 'w', encoding='utf-8') as f:
        json.dump(out, f, indent=1)


def report():
    setup = setup_mod.load()
    rows = sheet(setup)
    measured = {}
    for name in sorted(os.listdir(OUT_DIR)) if os.path.isdir(OUT_DIR) else []:
        with open(os.path.join(OUT_DIR, name), encoding='utf-8') as f:
            measured.update({m['id']: m for m in json.load(f)})
    readings = {str(r['ID']).strip(): r for r in setup.audit_readings}
    lines, inside, read, missing = [], 0, 0, []
    for r in rows:
        m = measured.get(r['Checkpoint'])
        floor = float(setup.settings[f"guide_{r['Class']}_min_won"])
        if m is None:
            missing.append(r['Checkpoint'])
            continue
        ok = m['won'] >= floor
        reading = readings.get(f"curve {r['Checkpoint']}")
        inside += ok
        read += (not ok) and reading is not None
        state = 'within' if ok else ('read: ' + str(reading['Result'])) if reading else '**below, unread**'
        lines.append(f"| {r['Checkpoint']} | {r['Boss']} | {r['Class']} | {m['level']} | {m['won']:.0%} | "
                     f"{floor:.0%} | {state} |")
    total = len(rows)
    text = ['# The story bosses against the guide (generated)', '',
            'Generated by `tools/guide_curve.py`. Do not edit: run the slices again, then `report`.', '',
            f'**Checklist: {inside} of {total} bosses within the floor of their class, {read} below and read, '
            f'{total - inside - read - len(missing)} below and unread, {len(missing)} not measured.**', '',
            'Vanilla data; the reference party at the reference level of each checkpoint. Class: what the GameFAQs '
            'guide says of the boss (sheet GuideDifficulty). Floor: the least win share that class allows.', '',
            '| Checkpoint | Boss | Class | Level | Won | Floor | State |', '|---|---|---|---|---|---|---|'] + lines
    with open(REPORT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(text) + '\n')
    print(text[4])


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    {'run': run, 'report': report}[sys.argv[1]](*sys.argv[2:])
