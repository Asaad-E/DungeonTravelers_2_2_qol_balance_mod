"""How much easier the variant is to win, party by party: seven parties at the bosses of the battery, in the game as it
is and on the variant, with enough battles for a difference in the share of wins to mean something. The three parties
that work in the game (Meta, Dual-Support, Mage-Heavy) carry the verdict; the four that lag behind in it (Juggernaut
and Anti-Meta, each with and without a Diva) are played to be read, not counted: lifting them is what the variant is
for. Nothing is written but the result.

    python measures/win_rates.py run [processes]      writes win_rates.json beside this file
    python measures/win_rates.py report               WIN_RATES.md beside this file

A cell is flagged when the variant wins 15 points more than the game: below that, two shares of this many battles
differ by chance (two standard errors of the difference are about 10 points at 200 battles, 14 at 100).
"""
import json
import math
import os
import sys
from concurrent.futures import ProcessPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(HERE)
sys.path.insert(0, PROJECT)
sys.path.insert(0, os.path.join(PROJECT, 'tools'))

PARTIES = {      # name: (roles, battles a cell, counted in the verdict)
    'Meta': ('valkyrie; dark lord; treasure hunter; papillon; diva', 200, True),
    'Dual-Support': ('tank; dark lord; shooter; healer; diva', 200, True),
    'Mage-Heavy': ('tank; mage; sage; healer; maid', 200, True),
    'Juggernaut': ('tank; attacker; dark lord; kunoichi; etoile', 100, False),
    'Juggernaut-Plus': ('tank; attacker; dark lord; kunoichi; diva', 100, False),
    'Anti-Meta': ('magical princess; mistress; soul summoner; joker; dolls', 100, False),
    'Anti-Meta-Plus': ('magical princess; mistress; soul summoner; dolls; diva', 100, False),
}
FLAG = 0.15
OUT, REPORT = os.path.join(HERE, 'win_rates.json'), os.path.join(HERE, 'WIN_RATES.md')
_STATE = {}


def _load():
    if not _STATE:
        from sim import setup as setup_mod
        from sim.data import game_data
        from sim.variant import balance_data
        vanilla = game_data()
        _STATE.update(setup=setup_mod.load(), sides={'vanilla': vanilla, 'variant': balance_data(vanilla)})
    return _STATE


def cell(task):
    party, cid, side = task
    from sim import scenario
    state = _load()
    roles = [r.strip() for r in PARTIES[party][0].split(';')]
    res = scenario.play_party(state['sides'][side], state['setup'], cid, roles, PARTIES[party][1])
    won = [r for r in res if r['won']]
    return {'party': party, 'id': cid, 'side': side, 'runs': len(res), 'won': len(won) / len(res),
            'time': sum(r['time'] for r in won) / len(won) if won else None}


def run(processes=12):
    from sim import setup as setup_mod
    bosses = [c.strip() for c in str(setup_mod.load().settings['battery_checkpoints']).split(';') if c.strip()]
    tasks = [(p, c, s) for p in PARTIES for c in bosses for s in ('vanilla', 'variant')]
    with ProcessPoolExecutor(int(processes)) as pool:
        cells = list(pool.map(cell, tasks, chunksize=2))
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump(cells, f, indent=1)
    print(len(cells), 'cells')


def report():
    with open(OUT, encoding='utf-8') as f:
        cells = json.load(f)
    at = {(c['party'], c['id'], c['side']): c for c in cells}
    bosses = sorted({c['id'] for c in cells})
    lines = ['# How much easier the variant is to win (generated by measures/win_rates.py)', '',
             'Share of wins, the game > the variant, and the difference in points. **Bold**: the variant wins 15 points '
             'more. The first three parties are counted; the last four lag behind in the game and are shown to be read.', '',
             '| Boss | ' + ' | '.join(PARTIES) + ' |', '|---|' + '---|' * len(PARTIES)]
    flagged, summary = [], {}
    for cid in bosses:
        row = []
        for party, (_, _, counted) in PARTIES.items():
            a, b = at[(party, cid, 'vanilla')], at[(party, cid, 'variant')]
            diff = b['won'] - a['won']
            text = f"{a['won']:.0%} > {b['won']:.0%} ({diff * 100:+.0f})"
            if diff >= FLAG:
                text = f'**{text}**'
                if counted:
                    flagged.append((cid, party, a['won'], b['won']))
            summary.setdefault(party, []).append((a['won'], b['won'], a['time'], b['time']))
            row.append(text)
        lines.append(f'| {cid} | ' + ' | '.join(row) + ' |')
    lines += ['', '| Party | Counted | Mean wins, game | Mean wins, variant | Bosses 15 points easier | Bosses below 50% in the game '
              '| of them, 50% or more on the variant | Fights shorter (both won) |', '|---|---|---|---|---|---|---|---|']
    for party, rows in summary.items():
        low = [r for r in rows if r[0] < 0.5]
        lengths = [1 - r[3] / r[2] for r in rows if r[2] and r[3]]
        lines.append(f"| {party} | {'yes' if PARTIES[party][2] else 'no'} | {sum(r[0] for r in rows) / len(rows):.0%} | "
                     f"{sum(r[1] for r in rows) / len(rows):.0%} | {sum(1 for r in rows if r[1] - r[0] >= FLAG)} | {len(low)} | "
                     f"{sum(1 for r in low if r[1] >= 0.5)} | {sum(lengths) / len(lengths):+.0%} |")
    se = lambda n: math.sqrt(2 * 0.25 / n)
    lines += ['', f'Two standard errors of a difference of shares near 50%: {2 * se(200) * 100:.0f} points at 200 battles, '
              f'{2 * se(100) * 100:.0f} at 100; less as a share nears 0% or 100%.']
    with open(REPORT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('\n'.join(lines[4:]))
    print()
    print('flagged, counted parties:', [(c, p, f'{a:.0%}>{b:.0%}') for c, p, a, b in flagged])


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    {'run': run, 'report': report}[sys.argv[1]](*sys.argv[2:])
