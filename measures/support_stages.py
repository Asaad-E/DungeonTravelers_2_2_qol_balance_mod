"""The supports and tanks at the stages where the party wins every fight, measured by what the party suffers in the
place of by its wins: tools/class_stages.py judges them by their share of wins in the contested fights, and the base
and intermediate stages have none. Each such role takes the last place of the reference party, as there; what is kept
is the lowest share of HP the party fell to during the fight, the share it ended with, and the length, each against
the median of the supports and tanks of the same checkpoint. Balance variant.

    python measures/support_stages.py [battles a cell, 60]      writes SUPPORT_STAGES.md beside this file
    python measures/support_stages.py [battles a cell, 60] --engine      the same, played by the C# engine (engine_cs/)
"""
import os
import statistics
import sys
from concurrent.futures import ProcessPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(HERE)
sys.path.insert(0, PROJECT)
sys.path.insert(0, os.path.join(PROJECT, 'tools'))

STAGES = ('base', 'intermediate')            # the stages whose rows read "no contested fight"
ENGINE = False                               # --engine: the cells are played by the C# engine
_STATE = {}


def _load():
    if not _STATE:
        from sim import setup as setup_mod
        from sim.data import game_data
        from sim.variant import balance_data
        _STATE.update(data=balance_data(game_data()), setup=setup_mod.load())
    return _STATE


def cell(task):
    cid, role, runs = task
    import class_stages
    state = _load()
    return cid, role, (class_stages.play_engine if ENGINE else class_stages.play)(state['data'], state['setup'], cid, role, runs)


def judged(setup, data):
    """{stage: ([checkpoints], [(role, class at the stage, kind)])} of the supports and tanks of the two stages."""
    import class_stages
    from sim import scenario
    by_class = class_stages.kinds()
    levels = scenario.reference_levels(data, setup)
    found = {}
    for st in class_stages.stages(setup):
        if st['Stage'] not in STAGES:
            continue
        cids = [c.strip() for c in str(st['Checkpoints']).split(';')]
        roles = []
        for role, row in setup.roles.items():
            cls = data.class_names[scenario.class_path(data, row, levels[cids[-1]][0])[0]]
            kind = 'support' if by_class.get(row['Lv30 class']) == 'support' else by_class.get(cls, 'attacker')
            if kind in ('support', 'tank'):
                roles.append((role, cls, kind))
        found[st['Stage']] = (cids, roles)
    return found


def main():
    global ENGINE
    ENGINE = '--engine' in sys.argv
    if ENGINE:
        sys.argv.remove('--engine')
    runs = int(sys.argv[1]) if len(sys.argv) > 1 else 60
    state = _load()
    plan = judged(state['setup'], state['data'])
    tasks = [(c, role, runs) for cids, roles in plan.values() for c in cids for role, _, _ in roles]
    with (__import__('engine_client').SerialPool() if ENGINE else ProcessPoolExecutor(12)) as pool:
        at = {(c, role): res for c, role, res in pool.map(cell, tasks)}
    out = ['# Supports and tanks where every fight is won (generated by measures/support_stages.py)', '',
           f'Balance variant, {runs} battles a cell. Each role in the last place of the reference party. Cells: the lowest '
           'share of HP the party fell to during the fight / the share it ended with / the length of the fight. The last '
           'columns are the mean over the checkpoints of the difference from the median role of the table: points of '
           'lowest HP (more is safer) and length (less is faster).', '']
    for stage, (cids, roles) in plan.items():
        out += [f'## {stage} ({", ".join(cids)})', '',
                '| Role | Class | Kind | ' + ' | '.join(cids) + ' | Wins | Lowest HP against the median | Length against the median |',
                '|' + '---|' * (6 + len(cids))]
        low = {c: statistics.median(at[(c, r)]['lowest_hp'] for r, _, _ in roles) for c in cids}
        time = {c: statistics.median(at[(c, r)]['time'] for r, _, _ in roles) for c in cids}
        for role, cls, kind in roles:
            mine = [at[(c, role)] for c in cids]
            cells = ' | '.join(f"{m['lowest_hp']:.0%} / {m['hp_left']:.0%} / {m['time']:.1f}" for m in mine)
            gap = sum(at[(c, role)]['lowest_hp'] - low[c] for c in cids) / len(cids)
            ratio = sum(at[(c, role)]['time'] / time[c] for c in cids) / len(cids)
            wins = min(m['won'] for m in mine)
            out.append(f'| {role} | {cls} | {kind} | {cells} | {wins:.0%} | {gap * 100:+.0f} | {ratio:.2f} |')
        out.append('')
    with open(os.path.join(HERE, 'SUPPORT_STAGES.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('\n'.join(out))


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    main()
