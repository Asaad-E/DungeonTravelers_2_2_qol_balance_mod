"""Whether each boss the variant made harder still needs it: the reference party at every checkpoint whose enemies
hold a live row of HP, ATK, DEF or INT in balance_changes.xlsx, in the game, on the variant, and on the variant with
those rows taken out. A boss that stands inside the windows of the game without its rows no longer needs them. The
windows are those of tools/difficulty_curve.py. Nothing is written but the report.

    python measures/boss_rows_check.py [battles, 200]      writes BOSS_ROWS_CHECK.md beside this file
    python measures/boss_rows_check.py [battles, 200] --engine      the same, played by the C# engine (engine_cs/)
"""
import os
import re
import sys
from concurrent.futures import ProcessPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(HERE)
sys.path.insert(0, PROJECT)
sys.path.insert(0, os.path.join(PROJECT, 'tools'))

FIELDS = ('hp', 'atk', 'def', 'int')
KEYS = ('won', 'time', 'lowest_hp', 'pressure')
ENGINE = False                               # --engine: the battles are played by the C# engine
_STATE = {}


def _load():
    if not _STATE:
        from sim import setup as setup_mod, variant
        from sim.data import game_data
        _STATE.update(vanilla=game_data(), setup=setup_mod.load(), rows=variant.rows(), variant=variant)
    return _STATE


def boss_rows(state):
    """{checkpoint: [rows]} of the live rows of enemy stats, by the checkpoint written in the record."""
    found = {}
    for row in state['rows']:
        if row['Table'] == 'enemies' and row['Field'] in FIELDS:
            where = re.search(r'\(([CP]\d+a?)\)', str(row['Record']))
            if where:
                found.setdefault(where.group(1), []).append(row)
    return found


def cell(task):
    cid, side, runs = task
    from sim import measures
    state = _load()
    variant = state['variant']
    if side == 'game':
        data = state['vanilla']
    else:
        mine = {r['ID'] for r in boss_rows(state).get(cid, [])} if side == 'without' else set()
        data = variant.apply(state['vanilla'], [r for r in state['rows'] if r['ID'] not in mine])
        data.arcane_chance = variant.arcane_chance()
        data.interrupt_product = variant.interrupt_product()
    return cid, side, (__import__('engine_client').play_checkpoint_sim if ENGINE else measures.play_checkpoint)(data, state['setup'], cid, runs)[1]


def out_of(setup, before, after):
    found = []
    for key in KEYS:
        width = float(setup.settings[f'check_{key}_window'])
        a, b = before[key], after[key]
        if a is None or b is None:
            continue
        if abs(b - a) > (width * a if key in ('time', 'pressure') else width):
            found.append(key)
    return found


def fmt(r):
    return f"{r['won']:.0%} / {r['time'] or 0:.1f} / {r['lowest_hp']:.0%}"


def main():
    global ENGINE
    ENGINE = '--engine' in sys.argv
    if ENGINE:
        sys.argv.remove('--engine')
    runs = int(sys.argv[1]) if len(sys.argv) > 1 else 200
    state = _load()
    rows = boss_rows(state)
    known = {c['ID'] for c in state['setup'].checkpoints}
    bosses = sorted(c for c in rows if c in known)
    tasks = [(c, s, runs) for c in bosses for s in ('game', 'variant', 'without')]
    with (__import__('engine_client').SerialPool() if ENGINE else ProcessPoolExecutor(12)) as pool:
        at = {(c, s): r for c, s, r in pool.map(cell, tasks)}
    out = ['# Whether each boss made harder still needs it (generated by measures/boss_rows_check.py)', '',
           f'The reference party, {runs} battles a cell: wins / length / lowest HP of the party. "Without its rows": the '
           'variant with the rows of HP, ATK, DEF and INT of that boss taken out. Out of the window: against the game, by the '
           'windows of tools/difficulty_curve.py.', '',
           '| Boss | Rows | The game | The variant | Out of the window | Without its rows | Out of the window | Reading |',
           '|---|---|---|---|---|---|---|---|']
    for c in bosses:
        game, var, bare = at[(c, 'game')], at[(c, 'variant')], at[(c, 'without')]
        with_rows, without = out_of(state['setup'], game, var), out_of(state['setup'], game, bare)
        change = '; '.join(sorted({f"{r['Field']} x{r['New'] / r['Vanilla']:.2f}" for r in rows[c]}))
        reading = 'not needed: within without them' if not without else 'needed' if len(with_rows) < len(without) else 'no better with them'
        out.append(f"| {c} | {change} | {fmt(game)} | {fmt(var)} | {', '.join(with_rows) or 'within'} | {fmt(bare)} | "
                   f"{', '.join(without) or 'within'} | {reading} |")
    with open(os.path.join(HERE, 'BOSS_ROWS_CHECK.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('\n'.join(out[4:]))


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    main()
