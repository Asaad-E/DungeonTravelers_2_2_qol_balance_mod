"""
The formulas the developers left written in the executable, generated into a document.

    python mod_project/tools/exe_formulas.py

Writes docs/generated/EXE_FORMULA_STRINGS.md: every debug message of the executable that holds
Japanese text and a format, with its address and the functions that refer to it. The battle code prints
each step of its calculations through these messages ("攻撃値Ａ : 自分ATK(%.3f) * (2 + 振れ幅(%.3f)) = "),
so they are the formulas in the developers' own words. docs/FORMULAS.md is their reading.
"""
import os
import re
import collections
from exe_reader import Exe

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT_PATH = os.path.join(os.path.dirname(BASE_DIR), 'docs', 'generated', 'EXE_FORMULA_STRINGS.md')
JAPANESE = re.compile(r'[぀-ヿ一-鿿]')


def japanese_strings(exe):
    """(address, text) of every NUL-terminated UTF-8 string with Japanese text in the data sections."""
    found = []
    for name, start, vsize, raw, rsize in exe.sections:
        if name not in ('.rdata', '.data'):
            continue
        blob = exe.data[raw:raw + rsize]
        pos = 0
        while pos < len(blob):
            end = blob.find(b'\x00', pos)
            if end == -1:
                break
            chunk = blob[pos:end]
            if len(chunk) >= 4:
                try:
                    text = chunk.decode('utf-8')
                    if JAPANESE.search(text) and all(c.isprintable() or c in '\n\t' for c in text):
                        found.append((start + pos, text))
                except UnicodeDecodeError:
                    pass
            pos = end + 1
    return found


def main():
    exe = Exe()
    strings = japanese_strings(exe)
    by_function = collections.defaultdict(list)
    loose = []
    for va, text in strings:
        if '%' not in text and not re.search(r'計算|率|値|補正|ダメージ', text):
            continue
        owners = sorted({exe.function_start(r) or 0 for r in exe.xrefs(va)})
        if owners:
            for owner in owners:
                by_function[owner].append((va, text))
        else:
            loose.append((va, text))
    lines = ['# Formula messages of the executable (generated)', '',
             'Generated by `tools/exe_formulas.py` from `DT22_en_unwrapped.exe`. Do not edit.',
             'Debug messages with Japanese text, grouped by the function that prints them, in address order.',
             'The reading of these messages is `docs/FORMULAS.md`.', '']
    for owner in sorted(by_function):
        lines += [f'## Function at `{owner:#010x}`', '']
        for va, text in sorted(set(by_function[owner])):
            lines.append(f'* `{va:#010x}` `{text.strip()}`')
        lines.append('')
    lines += ['## Not referred to by an absolute address', '',
              'Parts of longer messages that the code assembles, or messages reached through a table.', '']
    for va, text in loose:
        lines.append(f'* `{va:#010x}` `{text.strip()}`')
    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    with open(OUTPUT_PATH, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'Wrote {OUTPUT_PATH}: {sum(len(v) for v in by_function.values())} messages in {len(by_function)} functions, {len(loose)} loose')


if __name__ == '__main__':
    main()
