"""
The boss fights whose level the guides state, played by the reference party: docs/generated/SIM_ANCHORS.md.

    python mod_project/tools/sim_anchors.py

Each row of the sheet Anchors of data_tables/sim_setup.xlsx names a checkpoint (and, if it says so, other battles of
its floor), a party level and the share of wins the words of the guide stand for. The tool plays anchor_runs battles
for each and counts the rows whose win share falls inside their bounds. Nothing here holds a value.
"""
import os
import sys

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, BASE_DIR)
OUTPUT = os.path.join(BASE_DIR, 'docs', 'generated', 'SIM_ANCHORS.md')

from sim import scenario                                # noqa: E402
from sim import setup as setup_mod                      # noqa: E402
from sim.data import game_data                          # noqa: E402


def play_anchor(data, setup, row, runs):
    cid = row['Checkpoint']
    cp = setup.checkpoint(cid)
    level = row['Level (blank: reference level)']
    level = int(level) if level is not None else scenario.reference_levels(data, setup)[cid][0]
    battles = row['Battles (blank: those of the checkpoint)']
    numbers = [int(n) for n in str(battles).split('+')] if battles else scenario.battle_numbers(cp)
    gear = scenario.checkpoint_gear(data, setup, cid)

    def party():
        return scenario.reference_party(data, setup, cp['Chapter'], level, gear, int(cp['Crown bonus'] or 0),
                                        cp['Floor'])

    def enemies():
        return [scenario.fixed_battle(data, cp['Floor'], n) for n in numbers]

    results = scenario.play(data, setup, party, enemies, runs=runs)
    return level, numbers, sum(r['won'] for r in results) / runs


def main():
    data, setup = game_data(), setup_mod.load()
    runs = int(setup.settings['anchor_runs'])
    lines, met = [], 0
    rows = setup.anchors
    for row in rows:
        level, numbers, share = play_anchor(data, setup, row, runs)
        low = row['Lowest win share']
        high = row['Highest win share']
        ok = (low is None or share >= float(low)) and (high is None or share <= float(high))
        met += ok
        bounds = f'{"" if low is None else f"{float(low):.0%}"} - {"" if high is None else f"{float(high):.0%}"}'
        lines.append(f'| {row["ID"]} | {row["Checkpoint"]} | {"+".join(map(str, numbers))} | {level} | {share:.0%} | '
                     f'{bounds} | {"yes" if ok else "no"} | {row["What the source says, read as a win share"]} '
                     f'({row["Source"]}) |')
        print(f'{row["ID"]} {row["Checkpoint"]} level {level}: {share:.0%} ({"met" if ok else "not met"})', flush=True)
    out = ['# Anchors of the simulator (generated)', '',
           'Generated by `tools/sim_anchors.py` from the sheet `Anchors` of `data_tables/sim_setup.xlsx`. Do not edit: '
           'run the tool again.', '',
           f'Anchors met: **{met} of {len(rows)}**, {runs} battles each, with the settings of the workbook '
           f'(kit_count {setup.settings.get("kit_count")}).', '',
           '| ID | Checkpoint | Battles | Level | Won | Expected | Met | Source |', '|---|---|---|---|---|---|---|---|']
    out += lines
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')
    print(f'anchors met {met}/{len(rows)}; written {OUTPUT}')


if __name__ == '__main__':
    main()
