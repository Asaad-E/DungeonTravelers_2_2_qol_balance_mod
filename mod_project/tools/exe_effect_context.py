"""
Reading aid: for every effect the coverage tool lists as "located", what the program does right where it handles it.

    python mod_project/tools/exe_effect_context.py

Writes docs/generated/EFFECT_CONTEXT.md from the sheet EffectCoverage of balance_criteria.xlsx (run
tools/exe_effects.py first). For each place that asks for the effect, and for its own command if it has one, the
events that follow (tools/exe_digest.py): rolls, constants, stats, messages, other effects. It is material to
read a rule from, not the rule.
"""
import os
import sys

import openpyxl
import exe_digest
from exe_reader import Exe

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT_PATH = os.path.join(BASE_DIR, 'docs', 'generated', 'EFFECT_CONTEXT.md')
SPAN_PLACE, SPAN_COMMAND, KEEP = 0xA0, 0x260, 14


def main():
    exe = Exe()
    ws = openpyxl.load_workbook(os.path.join(BASE_DIR, 'data_tables', 'balance_criteria.xlsx'), read_only=True)['EffectCoverage']
    rows = list(ws.iter_rows(values_only=True))
    header = rows[0]
    lines = ['# What the program does where it handles each unread effect (generated)', '',
             'Generated by `tools/exe_effect_context.py`. Do not edit. A reading aid: the events after each place that asks for the '
             'effect (rolls, constants, stats, messages), and of its own command when it has one.', '']
    count = 0
    for r in rows[1:]:
        e = dict(zip(header, r))
        if e['State'] != 'located':
            continue
        count += 1
        lines += [f"## {e['Effect_ID']} {e['Effect']}  (skills {e['Skill_Uses']}, enemy attacks {e['EnemyAttack_Uses']})", '']
        if e['Own_Command']:
            start = int(e['Own_Command'], 16)
            events = exe_digest.digest(exe, start, start + SPAN_COMMAND)
            cut = next((k for k, ev in enumerate(events) if k > 3 and 'CREATE' in ev), len(events))
            lines += [f"own command `{e['Own_Command']}`:", '```'] + [ev[10:] for ev in events[:min(cut, KEEP + 8)]] + ['```']
        for place in [p for p in str(e['Other_Places'] or '').split(', ') if p][:4]:
            at = int(place, 16)
            events = [ev for ev in exe_digest.digest(exe, at, at + SPAN_PLACE)]
            lines += [f'asked at `{place}`:', '```'] + [ev[10:] for ev in events[:KEEP]] + ['```']
        lines.append('')
    with open(OUTPUT_PATH, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print(f'Wrote {OUTPUT_PATH}: {count} effects, {len(lines)} lines')


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    main()
