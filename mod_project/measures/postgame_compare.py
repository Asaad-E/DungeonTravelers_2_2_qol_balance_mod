"""The postgame on the variant against vanilla, boss by boss, at the preparation each fight asks for.

The reference party of the sheets loses most of the late postgame in vanilla too: it wears the gear of the guide but
none of the answers a Japanese player prepares for each fight. So that the two sides can be compared where the fight
is a fight, each boss is played at the least crown bonus (the steps below, starting at the one of the sheet
Checkpoints) at which the vanilla party reaches the floor of the class of the boss (sheet GuideDifficulty). The crown
bonus stands in for the preparation of the player: it adds to every stat and to the eight resistances. A model
choice, not a reading; the report says the step of each boss.

    python postgame_compare.py run k/n      one slice; writes postgame_compare_k.json beside this file
    python postgame_compare.py report       POSTGAME_COMPARE.md beside this file
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(HERE)
sys.path.insert(0, PROJECT)
sys.path.insert(0, os.path.join(PROJECT, 'tools'))
import guide_curve                                        # noqa: E402
from sim import measures, scenario, setup as setup_mod    # noqa: E402
from sim.data import game_data                            # noqa: E402
from sim.variant import balance_data                      # noqa: E402

STEPS = (0, 10, 20, 30, 40, 50)


def play(data, setup, cid, crown, runs):
    cp = setup.checkpoint(cid)
    level = scenario.reference_levels(data, setup)[cid][0]
    gear = scenario.checkpoint_gear(data, setup, cid)

    def party():
        return scenario.reference_party(data, setup, cp['Chapter'], level, gear, crown, cp['Floor'])

    def enemies():
        return [scenario.fixed_battle(data, cp['Floor'], n) for n in scenario.battle_numbers(cp)]

    return measures.summary(scenario.play(data, setup, party, enemies, runs=runs))


def run(part):
    k, n = (int(x) for x in part.split('/'))
    data, setup = game_data(), setup_mod.load()
    variant = balance_data(data)
    runs = int(setup.settings['check_runs'])
    rows = [r for r in guide_curve.sheet(setup) if r['Checkpoint'].startswith('P')]
    out = []
    for r in rows[(k - 1) * len(rows) // n: k * len(rows) // n]:
        cid = r['Checkpoint']
        floor = float(setup.settings[f"guide_{r['Class']}_min_won"])
        first = int(setup.checkpoint(cid)['Crown bonus'] or 0)
        crown = vanilla = None
        for crown in [s for s in STEPS if s >= first]:
            vanilla = play(data, setup, cid, crown, runs)
            if vanilla['won'] >= floor:
                break
        mod = play(variant, setup, cid, crown, runs)
        out.append({'id': cid, 'boss': r['Boss'], 'class': r['Class'], 'floor': floor, 'crown': crown,
                    'vanilla': vanilla, 'variant': mod})
        print(cid, crown, f"{vanilla['won']:.0%} > {mod['won']:.0%}", flush=True)
    with open(os.path.join(HERE, f'postgame_compare_{k}.json'), 'w', encoding='utf-8') as f:
        json.dump(out, f, indent=1)


def report():
    rows = []
    for name in os.listdir(HERE):
        if name.startswith('postgame_compare_') and name.endswith('.json'):
            with open(os.path.join(HERE, name), encoding='utf-8') as f:
                rows += json.load(f)
    rows.sort(key=lambda r: r['id'])

    def length(x):
        return f"{x['time']:.1f}" if x.get('time') else '-'

    reached = [r for r in rows if r['vanilla']['won'] >= r['floor']]
    easier = [r for r in reached if r['variant']['won'] - r['vanilla']['won'] > 0.15]
    harder = [r for r in reached if r['vanilla']['won'] - r['variant']['won'] > 0.15]
    lines = ['# The postgame on the variant against vanilla (generated by measures/postgame_compare.py)', '',
             f'**{len(rows)} bosses; vanilla reaches the floor of its class at {len(reached)} of them within a crown bonus '
             f'of 50; of those, the variant wins over 15 points more at {len(easier)} and over 15 points less at '
             f'{len(harder)}.**', '',
             'Crown: the least bonus at which the vanilla party reaches the floor (the preparation the fight asks for in '
             'the model; 50 where it never does).', '',
             '| Boss | Class | Crown | Wins, vanilla > variant | Length, vanilla > variant | Lowest HP |', '|---|---|---|---|---|---|']
    for r in rows:
        v, m = r['vanilla'], r['variant']
        mark = '' if r in reached else ' (floor not reached)'
        lines.append(f"| {r['id']} {r['boss']} | {r['class']} | {r['crown']}{mark} | {v['won']:.0%} > {m['won']:.0%} | "
                     f"{length(v)} > {length(m)} | {v['lowest_hp']:.0%} > {m['lowest_hp']:.0%} |")
    with open(os.path.join(HERE, 'POSTGAME_COMPARE.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(lines[2])


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    {'run': run, 'report': report}[sys.argv[1]](*sys.argv[2:])
