    /// <summary>measures/design_rows.py: figures for the rows of the register closed on a reading of the design; measures/DESIGN_ROWS.md. The game as it is.</summary>
    public static class DesignRows
    {
        // --- numbers that keep the kind they have in Python (an int stays an int) ----------------------------------
        static object Add(object a, object b) => a is long x && b is long y ? (object)(x + y) : Py.Num(a) + Py.Num(b);
        static object Mul(object a, object b) => a is long x && b is long y ? (object)(x * y) : Py.Num(a) * Py.Num(b);
        static bool Less(object a, object b) => Py.Num(a) < Py.Num(b);
        static int Compare(object a, object b)
        {
            if (a is string s && b is string t) return string.CompareOrdinal(s, t);
            return Py.Num(a).CompareTo(Py.Num(b));
        }

        static List<Obj> Sheet(Ctx c, string name) => c.In("design_rows").O("sheets").A(name).Cast<Obj>().ToList();

        // --- the battles ---------------------------------------------------------------------------------------------
        sealed class Spike { public string Cid; public double Median, Max, MedianMean, Won; }

        static List<string> Roles(string text) => text.Split(';').Select(r => r.Trim()).ToList();

        public static void Run(Ctx c)
        {
            var inp = c.In("design_rows");
            var data = c.Data("vanilla");
            var sc = c.Sc("vanilla");
            var parties = c.In("win_rates").O("parties");
            var swaps = inp.O("swaps");
            var story = c.Setup.Checkpoints.Select(r => r.Str("ID")).Where(id => id.StartsWith("C")).ToList();
            var walled = new List<string>();
            foreach (var cp in c.Setup.Checkpoints)
                if (Scenario.BattleNumbers(cp).Any(n => sc.BattleZone(cp.Str("Floor"), n)?.NoMagic == true)) walled.Add(cp.Str("ID"));
            var noTreasure = parties.Where(kv => !((string)((List<object>)kv.Value)[0]).Contains("treasure hunter")).Select(kv => kv.Key).ToList();
            var names = new List<string>(noTreasure); names.AddRange(swaps.Keys);
            var jobs = new List<JobSpec>();
            foreach (var cid in story) jobs.Add(Jb.Make(c, "vanilla", cid, runs: 30, record: true, name: cid));
            foreach (var p in names)
                foreach (var cid in walled)
                {
                    string roles = swaps.Has(p) && Py.Truthy(swaps.Get(p)) ? (string)swaps.Get(p) : (string)((List<object>)parties.Get(p))[0];
                    jobs.Add(Jb.Make(c, "vanilla", cid, roles: Roles(roles), runs: 100, name: p + "|" + cid));
                }
            var done = c.Run(jobs);
            var spikes = new List<Spike>();
            for (int k = 0; k < story.Count; k++)
            {
                string cid = story[k];
                var members = sc.PartyOfRoles(cid, c.Setup.Composition, null, null).Where(u => u.Kind == Kind.Member).ToList();
                double frail = members.Min(u => u.MaxHp), mean = (double)members.Sum(u => (long)u.MaxHp) / members.Count;
                var hits = new List<double>();
                foreach (var r in done[k].Runs)
                {
                    double top = 0; bool any = false;
                    foreach (var part in r.Parts)
                    {
                        var table = part.Record.LargestHit;
                        for (int i = 0; i < table.Count; i++) { if (!any || table.Values[i] > top) top = table.Values[i]; any = true; }
                    }
                    hits.Add(any ? top : 0);
                }
                double median = Py.Median(hits);
                spikes.Add(new Spike { Cid = cid, Median = median / frail, Max = hits.Max() / frail, MedianMean = median / mean, Won = (double)done[k].Runs.Count(r => r.Won) / done[k].Runs.Length });
            }
            var won = new Dictionary<(string, string), double>();
            int at = story.Count;
            foreach (var p in names) foreach (var cid in walled) { var res = done[at++].Runs; won[(p, cid)] = (double)res.Count(r => r.Won) / res.Length; }

            var o = new List<string>
            {
                "# Figures for the rows closed on a reading of the design (generated by measures/design_rows.py)", "",
                "The game as it is. Each section answers the test its row of the register names.", "",
            };
            var over = spikes.Where(s => s.Max >= 1).ToList();
            var usual = spikes.Where(s => s.Median >= 1).ToList();
            o.AddRange(new[]
            {
                "## J17 Area damage spikes", "",
                "The reference party at the " + spikes.Count + " boss fights of the story, 30 battles each, guards and Cover played as its policy has them. The largest damage one enemy action did to one member, against the max HP of the frailest member: at least once above her whole HP in "
                    + over.Count + " fights, and in the median battle in " + usual.Count + " (" + string.Join(", ", usual.Select(s => s.Cid)) + "). The action may be an area attack or several hits on one member.", "",
                "| Boss | Median largest hit / HP of the frailest | Largest seen | Median / mean HP of the party | Wins |", "|---|---|---|---|---|",
            });
            foreach (var s in spikes) if (s.Max >= 0.75) o.Add("| " + s.Cid + " | " + Py.Pct(s.Median, 0) + " | " + Py.Pct(s.Max, 0) + " | " + Py.Pct(s.MedianMean, 0) + " | " + Py.Pct(s.Won, 0) + " |");
            o.AddRange(new[] { "", "Fights where no hit reached 75% of her HP are left out of the table.", "" });
            o.AddRange(new[]
            {
                "## F95 Anti-magic bosses", "",
                "Boss fights that stand on a cell that forbids magic: " + string.Join(", ", walled) + ". Share of wins of the parties with no Treasure Hunter, 100 battles:", "",
                "| Party | " + string.Join(" | ", walled) + " |", "|---|" + string.Concat(walled.Select(x => "---|")),
            });
            foreach (var p in noTreasure) o.Add("| " + p + " | " + string.Join(" | ", walled.Select(cid => Py.Pct(won[(p, cid)], 0))) + " |");
            o.AddRange(new[] { "", "The same party with and without her:", "", "| Party | " + string.Join(" | ", walled) + " |", "|---|" + string.Concat(walled.Select(x => "---|")) });
            foreach (var p in swaps.Keys) o.Add("| " + p + " | " + string.Join(" | ", walled.Select(cid => Py.Pct(won[(p, cid)], 0))) + " |");
            o.Add("");
            Zones(c, o);
            Forging(c, o);
            Economy(c, o);
            Meals(c, o);
            c.WriteText(c.Path("measures", "DESIGN_ROWS.md"), M.Lines(o), true);
        }

        // --- the sections that read the data -------------------------------------------------------------------------
        static void Zones(Ctx c, List<string> o)
        {
            var inp = c.In("design_rows");
            var maps = inp.O("maps");
            long noMagic = inp.L("no_magic");
            var down = inp.A("down").Select(x => (long)Py.Num(x)).ToList();
            var count = new Dictionary<string, int>(); var shares = new Dictionary<string, List<double>> { { "no magic", new List<double>() }, { "lowers an attack", new List<double>() } };
            foreach (var kv in maps)
            {
                var cells = (List<object>)kv.Value;
                foreach (var (label, wanted) in new[] { ("no magic", new HashSet<long> { noMagic }), ("lowers an attack", new HashSet<long>(down)) })
                {
                    int hit = cells.Count(cell => ((List<object>)cell).Any(s => wanted.Contains((long)Py.Num(s))));
                    if (hit > 0) { count[label] = count.GetValueOrDefault(label) + 1; shares[label].Add((double)hit / cells.Count); }
                }
            }
            var factors = new SortedSet<double>();
            foreach (Obj f in inp.A("floors"))
                if (f.Get("down") is List<object> pair) foreach (var v in pair) factors.Add(PyMath.RoundTo(Py.Num(v), 2));
            var downs = factors.ToList();
            o.AddRange(new[]
            {
                "## S14 Harmful map zones", "",
                "Of the " + maps.Count + " floors of the game, " + count["no magic"] + " have cells that forbid magic and " + count["lowers an attack"]
                    + " have cells that lower physical or magic attack. Where a floor has them they cover a median of " + Py.Pct(Py.Median(shares["no magic"]), 0) + " (no magic) and "
                    + Py.Pct(Py.Median(shares["lowers an attack"]), 0) + " (lowered attack) of all the cells of its map, walls counted, at most " + Py.Pct(shares["no magic"].Max(), 0) + " and "
                    + Py.Pct(shares["lowers an attack"].Max(), 0) + ". A lowering zone multiplies attack by " + Py.Repr(downs[0]) + " to " + Py.Repr(downs[downs.Count - 1]) + " for both sides (docs/FORMULAS.md 2.5).", "",
            });
        }

        static void Forging(Ctx c, List<string> o)
        {
            var data = c.Data("vanilla");
            var eq = Sheet(c, "Equipment");
            var plain = eq.Where(e => Py.Truthy(e.Get("Upgrade_Rate"))).ToList();
            var fixedPieces = eq.Where(e => !Py.Truthy(e.Get("Upgrade_Rate"))).ToList();
            var weapons = plain.Where(e => (string)e.Get("Category") == "Weapon" && Py.Truthy(e.Get("ATK"))).ToList();
            var step = weapons.Select(e => Py.Num(e.Get("Upgrade_Rate")) / Py.Num(e.Get("ATK"))).OrderBy(x => x).ToList();
            var byDungeon = new Dictionary<string, int>();
            foreach (var f in data.Floors)
            {
                int top = 0; bool any = false;
                foreach (var p in f.Equipment) foreach (var (_, lo, hi) in p.levels) { if (!any || hi > top) top = hi; any = true; }
                byDungeon[f.Dungeon] = Math.Max(byDungeon.GetValueOrDefault(f.Dungeon, 0), any ? top : 0);
            }
            int topLevel = byDungeon.Values.Max();
            var counts = fixedPieces.Select(e => e.Get("Enchant_Count")).ToList();
            object min = counts[0], max = counts[0];
            foreach (var v in counts) { if (Less(v, min)) min = v; if (Less(max, v)) max = v; }
            o.AddRange(new[]
            {
                "## J35 Forging, S16 Forged pieces against unique ones", "",
                plain.Count + " of the " + eq.Count + " pieces of equipment take upgrade levels (" + weapons.Count + " of them weapons with ATK, none with an enchantment of its own); the other " + fixedPieces.Count
                    + " are fixed pieces with " + Py.Str(min) + " to " + Py.Str(max) + " enchantments and no upgrade. Each level adds `int(level * rate)` to every stat the piece has (docs/FORMULAS.md 10.1): for a weapon "
                    + Py.Pct(step[0], 1) + " to " + Py.Pct(step[step.Count - 1], 1) + " of its base ATK a level, median " + Py.Pct(Py.Median(step), 1) + ". The highest level a zone gives is " + topLevel + ".", "",
                "| Weapon type | Best piece that takes levels | Its ATK at +0 | at the top level | Best fixed piece | Its ATK |", "|---|---|---|---|---|---|",
            });
            var kinds = new List<(object kind, Dictionary<string, Obj> found)>();
            foreach (var e in eq)
            {
                if (!((string)e.Get("Category") == "Weapon" && Py.Truthy(e.Get("ATK")))) continue;
                string key = Py.Truthy(e.Get("Upgrade_Rate")) ? "plain" : "fixed";
                var code = e.Get("Type_Code");
                int at = kinds.FindIndex(k => Compare(k.kind, code) == 0 && (k.kind is string) == (code is string));
                if (at < 0) { kinds.Add((code, new Dictionary<string, Obj>())); at = kinds.Count - 1; }
                var found = kinds[at].found;
                if (!found.ContainsKey(key) || Less(found[key].Get("ATK"), e.Get("ATK"))) found[key] = e;
            }
            int above = 0, pairs = 0;
            foreach (var (kind, found) in kinds.OrderBy(k => k.kind, Comparer<object>.Create(Compare)))
            {
                if (!(found.ContainsKey("plain") && found.ContainsKey("fixed"))) continue;
                var p = found["plain"]; var f = found["fixed"];
                object forged = Add(p.Get("ATK"), (long)PyMath.Long(Py.Num(Mul((long)topLevel, p.Get("Upgrade_Rate")))));
                pairs++;
                if (Py.Num(forged) > Py.Num(f.Get("ATK"))) above++;
                o.Add("| " + Py.Str(kind) + " | " + Py.Str(p.Get("Name")) + " | " + Py.Str(p.Get("ATK")) + " | " + Py.Str(forged) + " | " + Py.Str(f.Get("Name")) + " | " + Py.Str(f.Get("ATK")) + " |");
            }
            o.AddRange(new[] { "", "At the top level the plain piece has more ATK than the best fixed one in " + above + " of " + pairs + " weapon types. What an upgrade level costs in gold is in the program and was not read.", "" });
        }

        static void Economy(Ctx c, List<string> o)
        {
            var data = c.Data("vanilla");
            var items = new Dictionary<string, Obj>();
            foreach (var i in Sheet(c, "Items")) items[Py.Str(i.Get("Name"))] = i;
            var by = new SortedDictionary<string, List<double>>(StringComparer.Ordinal);
            foreach (var f in data.Floors)
            {
                if (f.Formations.Length < 2) continue;
                long total = f.Formations.Sum(x => Math.Max(1L, (long)x.Chance));
                long gold = 0;
                foreach (var x in f.Formations)
                    gold += Math.Max(1L, (long)x.Chance) * x.Enemies.Where(e => data.Enemies.ContainsKey(e.enemy)).Sum(e => (long)data.Enemies[e.enemy].Gold);
                if (!by.ContainsKey(f.Dungeon)) by[f.Dungeon] = new List<double>();
                by[f.Dungeon].Add((double)gold / total);
            }
            o.AddRange(new[] { "## S19 Early economy", "", "Gold of one random battle, the mean over the formations of each zone by their chance, by dungeon in the order of the files:", "", "| Dungeon | Gold a battle (lowest zone - highest) |", "|---|---|" });
            foreach (var dungeon in by.Keys.Take(6)) o.Add("| " + dungeon + " | " + Py.F(by[dungeon].Min(), 0) + " - " + Py.F(by[dungeon].Max(), 0) + " |");
            var cheap = new[] { "Croissant", "Danish", "Egg Sandwich", "Gateau Au Chocolat" }.Where(items.ContainsKey).Select(n => items[n]).ToList();
            o.AddRange(new[] { "", "Shop prices: " + string.Join(", ", cheap.Select(i => Py.Str(i.Get("Name")) + " " + Py.Str(i.Get("Buy_Price")))) + ". A piece sells for a third of its price. The prices of equipment are not decoded.", "" });
        }

        static void Meals(Ctx c, List<string> o)
        {
            var inp = c.In("design_rows");
            var data = c.Data("vanilla");
            long stepsATurn = inp.L("steps_a_turn");
            var buffs = inp.O("buffs");
            var food = Sheet(c, "FoodMenu");
            var lines = new List<string>();
            object shortest = null, longest = null;
            int withBuff = 0;
            foreach (var meal in food)
            {
                var kinds = new List<string>();
                for (int k = 1; k <= 5; k++)
                {
                    var v = meal.Get("Eff" + k + "_ID");
                    if (v == null) continue;
                    string key = v is double d && d == Math.Floor(d) ? ((long)d).ToString() : Py.Str(v);
                    if (buffs.Has(key)) kinds.Add(key);
                }
                if (kinds.Count == 0) continue;
                withBuff++;
                var parts = new List<string>();
                foreach (var kind in kinds)
                {
                    var buff = buffs.O(kind);
                    object turns = buff.Get("turns");
                    object steps = Mul(turns, stepsATurn);
                    object a = Py.Truthy(shortest) ? shortest : steps, b = Py.Truthy(longest) ? longest : steps;
                    shortest = Py.Num(steps) <= Py.Num(a) ? steps : a;
                    longest = Py.Num(steps) >= Py.Num(b) ? steps : b;
                    parts.Add(buff.S("name") + " Lv" + Py.Str(buff.Get("level")) + ": " + Py.Str(turns) + " turns, " + Py.Str(steps) + " steps");
                }
                lines.Add("| " + Py.Str(meal.Get("Name")) + " | " + Py.Str(meal.Get("Price")) + " | " + string.Join("; ", parts) + " |");
            }
            var walk = new List<double>();
            foreach (Obj f in inp.A("floors")) if (Py.Truthy(f.Get("encounter"))) walk.Add(8 + 100.0 / Py.Num(f.Get("encounter")));
            walk.Sort();
            o.AddRange(new[]
            {
                "## J36 Meals", "",
                food.Count + " meals; " + withBuff + " give a buff, the others only restore or cure at once. The buff is the status of a skill at a fixed level (tools/item_effect_data.py), with the turns that skill has at that level, and on the map a turn of a status is "
                    + stepsATurn + " steps (docs/FORMULAS.md 12.18). So a meal lasts " + Py.Str(shortest) + " to " + Py.Str(longest) + " steps; in a battle each action of its bearer takes a turn off it. The mean walk between two random battles is "
                    + Py.F(walk[0], 0) + " to " + Py.F(walk[walk.Count - 1], 0) + " steps by zone (median " + Py.F(Py.Median(walk), 0) + "): a meal is worth about one battle, and reaches a boss only when the shop appears at its door.", "",
                "| Meal | Price | Buff |", "|---|---|---|",
            });
            o.AddRange(lines);
            o.Add("");
        }
    }
