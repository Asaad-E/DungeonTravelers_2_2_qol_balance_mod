    /// <summary>measures/random_battles.py: rows of random battles of the floor of every checkpoint, vanilla against the variant; measures/RANDOM_BATTLES.md.</summary>
    public static class RandomBattles
    {
        static string Head(string name)
        {
            int at = name.IndexOf(" zone", StringComparison.Ordinal);
            return at < 0 ? name : name.Substring(0, at);
        }

        static string Four(string name) => name.Length <= 4 ? name : name.Substring(0, 4);

        /// <summary>The zones the rows draw from (null when the floor has none).</summary>
        static List<FloorZone> ZonesOf(Ctx c, string side, string cid, int ahead)
        {
            var data = c.Data(side);
            var sc = c.Sc(side);
            var cp = c.Checkpoint(cid);
            string floor = cp.Str("Floor");
            int level = sc.ReferenceLevels()[cid].level;
            var zones = data.Floors.Where(z => Head(z.Name) == floor && z.Formations.Length > 0).ToList();
            if (zones.Count == 0) zones = data.Floors.Where(z => Four(z.Name) == Four(floor) && z.Formations.Length > 0).ToList();
            if (zones.Count == 0) return null;
            // a floor may hold a zone that opens later in the story: the zones whose enemies stand more than `ahead` levels over the party are left out
            var probe = new PyRandom(5);
            var near = new List<FloorZone>();
            foreach (var z in zones)
            {
                int top = int.MinValue;
                for (int i = 0; i < 12; i++) foreach (var u in sc.RandomGroup(z, probe).Units) top = Math.Max(top, u.Level);
                if (top <= level + ahead) near.Add(z);
            }
            return near.Count > 0 ? near : zones;
        }

        public static void Run(Ctx c, int rows = 20)
        {
            int chain = (int)c.In("random_battles").L("chain"), ahead = (int)c.In("random_battles").L("ahead");
            var ids = DifficultyCurve.Checkpoints(c);
            var jobs = new List<JobSpec>(); var index = new Dictionary<(string, string), int>();
            foreach (var cid in ids)
                foreach (var side in new[] { "vanilla", "variant" })
                {
                    var zones = ZonesOf(c, side, cid, ahead);
                    if (zones == null) continue;
                    index[(cid, side)] = jobs.Count;
                    jobs.Add(Jb.Make(c, side, cid, runs: rows, name: cid + "|" + side, enemies: Jb.Chain(zones.Select(z => z.Name), 11, chain)));
                }
            var done = c.Run(jobs);
            Func<string, string, object> figures = (cid, side) =>
            {
                if (!index.TryGetValue((cid, side), out int at)) return null;
                var res = done[at].Runs;
                var won = res.Where(r => r.Won).ToList();
                return new Obj
                {
                    { "level", (long)c.Sc(side).ReferenceLevels()[cid].level }, { "won", (double)won.Count / res.Length },
                    { "time", won.Count > 0 ? (object)(Py.Sum(won.Select(r => r.Time)) / won.Count / chain) : null }, { "hp_left", Py.Sum(res.Select(r => r.HpLeft)) / res.Length },
                };
            };
            var outRows = ids.Select(cid => (object)new Obj { { "id", cid }, { "vanilla", figures(cid, "vanilla") }, { "variant", figures(cid, "variant") } }).ToList();
            foreach (var name in M.Listing(c.Path("measures"))) if (name.StartsWith("random_battles_") && name.EndsWith(".json")) File.Delete(c.Path("measures", name));
            c.WriteText(c.Path("measures", "random_battles_1.json"), PyJson.Dump(outRows, 1), false);
        }

        public static void Report(Ctx c)
        {
            int chain = (int)c.In("random_battles").L("chain");
            var order = DifficultyCurve.Checkpoints(c);
            var rows = Parts.Read(c, "random_battles").Where(r => r.Get("vanilla") != null).OrderBy(r => order.IndexOf(r.S("id"))).ToList();
            var lines = new List<string>
            {
                "# Random battles along the game, vanilla against the variant (generated by measures/random_battles.py)", "",
                "Rows of " + chain + " random battles in a row at the floor of each checkpoint, the reference party at its reference level. Rows survived; mean length of a battle of the rows survived; share of HP the party ends the row with.", "",
                "| Floor of | Level | Rows survived | Length of a battle | HP left |", "|---|---|---|---|---|",
            };
            var shorter = new List<double>();
            foreach (var r in rows)
            {
                var a = r.O("vanilla"); var b = r.O("variant");
                bool both = Py.Truthy(a.Get("time")) && Py.Truthy(b.Get("time"));
                string length = both ? Py.F(a.D("time"), 1) + " > " + Py.F(b.D("time"), 1) : "-";
                if (both) shorter.Add(1 - b.D("time") / a.D("time"));
                lines.Add("| " + r.S("id") + " | " + Py.Str(a.Get("level")) + " | " + Py.Pct(a.D("won"), 0) + " > " + Py.Pct(b.D("won"), 0) + " | " + length + " | " + Py.Pct(a.D("hp_left"), 0) + " > " + Py.Pct(b.D("hp_left"), 0) + " |");
            }
            double mean = shorter.Count > 0 ? Py.Sum(shorter) / shorter.Count : 0.0;
            lines.Insert(4, "**" + rows.Count + " floors; a battle is " + Py.Pct(mean, 0) + " shorter on the variant in the mean (" + Py.Pct(shorter.Min(), 0) + " to " + Py.Pct(shorter.Max(), 0) + ").**");
            lines.Insert(5, "");
            c.WriteText(c.Path("measures", "RANDOM_BATTLES.md"), M.Lines(lines), true);
        }
    }

    /// <summary>measures/regression_r04.py: condition R04 of the sheet Regression (no mandatory class); measures/REGRESSION_R04.md.</summary>
    public static class RegressionR04
    {
        static Obj Classes(Ctx c, string side, string cid, IEnumerable<string> roles)
        {
            var sc = c.Sc(side);
            int level = sc.ReferenceLevels()[cid].level;
            var o = new Obj();
            foreach (var role in roles) o.Set(role, c.Data(side).ClassName(sc.ClassPath(c.Setup.Roles[role], level).cls));
            return o;
        }

        static bool Holds(Obj held, string cls) => held.Any(kv => (string)kv.Value == cls);

        static Dictionary<string, double> Floors(Ctx c, IEnumerable<string> ids) => ids.Distinct().ToDictionary(x => x, x => M.Floor(c, x));

        static List<Obj> BatteryRows(Ctx c)
        {
            string dir = c.Path("docs", "generated", "party_battery");
            var rows = new List<Obj>();
            foreach (var name in M.Listing(dir)) if (name.StartsWith("part_") && name.EndsWith(".json")) rows.AddRange(((List<object>)c.ReadJson(Path.Combine(dir, name))).Cast<Obj>());
            return rows;
        }

        public static void Run(Ctx c, int runs = 60)
        {
            var rows = BatteryRows(c);
            var ids = rows.Select(r => r.S("id")).Distinct().OrderBy(x => x, StringComparer.Ordinal).ToList();
            var floor = Floors(c, ids);
            var substitutes = c.In("regression_r04").O("substitutes");
            // the pairs of boss and class that every winning party holds
            var found = new List<(string cid, string side, string cls, List<string> winners)>();
            foreach (var cid in ids)
                foreach (var side in new[] { "vanilla", "variant" })
                {
                    var winners = new List<(string party, Obj held)>();
                    foreach (var r in rows)
                    {
                        if (r.S("id") != cid) continue;
                        var s = r.O(side);
                        if ((double)s.L("wins") / s.L("runs") >= floor[cid])
                        {
                            var roles = s.A("members").Select(m => ((string)m).Split('(')[1].TrimEnd(')'));
                            winners.Add((r.S("party"), Classes(c, "vanilla", cid, roles)));
                        }
                    }
                    var every = new SortedSet<string>(winners.SelectMany(w => w.held.Select(kv => (string)kv.Value)), StringComparer.Ordinal);
                    foreach (var cls in every)
                        if (winners.All(w => Holds(w.held, cls))) found.Add((cid, side, cls, winners.Select(w => w.party).ToList()));
                }
            // the trials of each pair, in the order the tool tries them: the parties that won, the neighbours of the role that holds the class
            var pairs = new List<(string cid, string side, string cls, List<(string text, List<string> trial)> trials)>();
            foreach (var (cid, side, cls, winners) in found)
            {
                var trials = new List<(string, List<string>)>();
                var sc = c.Sc(side);
                foreach (var name in winners)
                {
                    var roles = c.Setup.Battery.First(b => b.name == name).roles;
                    var held = Classes(c, side, cid, roles);
                    var mine = roles.Where(r => (string)held.Get(r) == cls).ToList();
                    if (mine.Count == 0 || !substitutes.Has(mine[0])) continue;
                    foreach (string nw in substitutes.A(mine[0]))
                    {
                        var trial = roles.Select(r => mine.Contains(r) ? nw : r).ToList();
                        if (Holds(Classes(c, side, cid, trial), cls) || trial.Distinct().Count() < trial.Count) continue;
                        var units = sc.PartyOfRoles(cid, trial, null, null);
                        if (units.Any(u => (u.ClassId == T.NONE ? null : c.Data(side).ClassName(u.ClassId)) == cls)) continue;      // a fallback member brought the class back
                        trials.Add((name + " with " + nw + " for " + mine[0], trial));
                    }
                }
                pairs.Add((cid, side, cls, trials));
            }
            var at = new int[pairs.Count]; var done = new bool[pairs.Count]; var best = new (double won, string text)?[pairs.Count];
            while (true)
            {
                var active = Enumerable.Range(0, pairs.Count).Where(i => !done[i] && at[i] < pairs[i].trials.Count).ToList();
                if (active.Count == 0) break;
                var jobs = active.Select(i => Jb.Make(c, pairs[i].side, pairs[i].cid, roles: pairs[i].trials[at[i]].trial, runs: runs, name: pairs[i].cid + "|" + i + "|" + at[i])).ToList();
                var played = c.Run(jobs);
                for (int k = 0; k < active.Count; k++)
                {
                    int i = active[k];
                    double won = Summary.Of(played[k].Runs.ToList()).Won;
                    if (best[i] == null || won > best[i].Value.won) best[i] = (won, pairs[i].trials[at[i]].text);
                    if (won >= floor[pairs[i].cid]) done[i] = true;
                    at[i]++;
                }
            }
            var outRows = new List<object>();
            for (int i = 0; i < pairs.Count; i++)
                outRows.Add(new Obj
                {
                    { "id", pairs[i].cid }, { "side", pairs[i].side }, { "class", pairs[i].cls }, { "floor", floor[pairs[i].cid] },
                    { "won", best[i] != null ? (object)best[i].Value.won : null }, { "party", best[i] != null ? best[i].Value.text : null },
                });
            c.WriteText(c.Path("measures", "regression_r04_1.json"), PyJson.Dump(outRows, 1), false);
        }

        public static void Report(Ctx c)
        {
            var rows = Parts.Read(c, "regression_r04");
            rows = rows.OrderBy(r => r.S("id"), StringComparer.Ordinal).ThenBy(r => r.S("side"), StringComparer.Ordinal).ThenBy(r => r.S("class"), StringComparer.Ordinal).ToList();
            Func<string, (int reached, int total)> count = side => (rows.Count(r => r.S("side") == side && r.Get("won") != null && r.D("won") >= r.D("floor")), rows.Count(r => r.S("side") == side));
            var variant = count("variant"); var vanilla = count("vanilla");
            var lines = new List<string>
            {
                "# Regression R04: no mandatory class (generated by measures/regression_r04.py)", "",
                "The pairs of boss and class that every winning party of the battery holds, and the best party found without that class (the role changed for a neighbour of the same job).", "",
                "**A party without the class reaches the floor at " + variant.reached + " of " + variant.total + " such pairs on the variant, " + vanilla.reached + " of " + vanilla.total + " in vanilla.**", "",
                "| Boss | Side | Class | Floor | Best party without it | Wins |", "|---|---|---|---|---|---|",
            };
            foreach (var r in rows)
            {
                string won = r.Get("won") == null ? "-" : Py.Pct(r.D("won"), 0);
                string mark = r.Get("won") != null && r.D("won") >= r.D("floor") ? "" : " **below**";
                lines.Add("| " + r.S("id") + " | " + r.S("side") + " | " + r.S("class") + " | " + Py.Pct(r.D("floor"), 0) + " | " + (Py.Truthy(r.Get("party")) ? r.S("party") : "none could be built") + " | " + won + mark + " |");
            }
            c.WriteText(c.Path("measures", "REGRESSION_R04.md"), M.Lines(lines), true);
        }
    }
