using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

namespace DtEngine.Suite
{
    /// <summary>measures/win_rates.py: seven parties at the bosses of the battery, in the game and on the variant; measures/WIN_RATES.md.</summary>
    public static class WinRates
    {
        public static List<(string name, string roles, int runs, bool counted)> Parties(Ctx c) =>
            c.In("win_rates").O("parties").Select(kv => { var a = (List<object>)kv.Value; return (kv.Key, (string)a[0], (int)Py.Num(a[1]), Py.Truthy(a[2])); }).ToList();

        public static List<string> Roles(string text) => text.Split(';').Select(r => r.Trim()).ToList();

        public static void Run(Ctx c)
        {
            var parties = Parties(c);
            var bosses = PartyBattery.Checkpoints(c);
            var tasks = new List<(string party, string cid, string side, string roles, int runs)>();
            foreach (var p in parties) foreach (var cid in bosses) foreach (var side in new[] { "vanilla", "variant" }) tasks.Add((p.name, cid, side, p.roles, p.runs));
            var jobs = tasks.Select(t => Jb.Make(c, t.side, t.cid, roles: Roles(t.roles), runs: t.runs, name: t.party + "|" + t.cid + "|" + t.side)).ToList();
            var played = c.Run(jobs);
            var cells = new List<object>();
            for (int k = 0; k < tasks.Count; k++)
            {
                var res = played[k].Runs;
                var won = res.Where(r => r.Won).ToList();
                cells.Add(new Obj
                {
                    { "party", tasks[k].party }, { "id", tasks[k].cid }, { "side", tasks[k].side }, { "runs", (long)res.Length },
                    { "won", (double)won.Count / res.Length }, { "time", won.Count > 0 ? (object)(Py.Sum(won.Select(r => r.Time)) / won.Count) : null },
                });
            }
            c.WriteText(c.Path("measures", "win_rates.json"), PyJson.Dump(cells, 1), false);
        }

        public static void Report(Ctx c)
        {
            var parties = Parties(c);
            double flag = c.In("win_rates").D("flag"), lowBelow = c.In("win_rates").D("low_below");
            var cells = ((List<object>)c.ReadJson(c.Path("measures", "win_rates.json"))).Cast<Obj>().ToList();
            var at = new Dictionary<(string, string, string), Obj>();
            foreach (var cell in cells) at[(cell.S("party"), cell.S("id"), cell.S("side"))] = cell;
            var bosses = cells.Select(x => x.S("id")).Distinct().ToList();
            bosses.Sort(string.CompareOrdinal);
            var lines = new List<string>
            {
                "# How much easier the variant is to win (generated by measures/win_rates.py)", "",
                "Share of wins, the game > the variant, and the difference in points. **Bold**: the variant wins 15 points more. The first three parties are counted; the last four lag behind in the game and are shown to be read.", "",
                "| Boss | " + string.Join(" | ", parties.Select(p => p.name)) + " |", "|---|" + string.Concat(parties.Select(p => "---|")),
            };
            var summary = new Dictionary<string, List<(double a, double b, double? ta, double? tb)>>();
            foreach (var p in parties) summary[p.name] = new List<(double, double, double?, double?)>();
            foreach (var cid in bosses)
            {
                var row = new List<string>();
                foreach (var p in parties)
                {
                    var a = at[(p.name, cid, "vanilla")]; var b = at[(p.name, cid, "variant")];
                    double diff = b.D("won") - a.D("won");
                    string text = Py.Pct(a.D("won"), 0) + " > " + Py.Pct(b.D("won"), 0) + " (" + Py.F(diff * 100, 0, true) + ")";
                    if (diff >= flag) text = "**" + text + "**";
                    summary[p.name].Add((a.D("won"), b.D("won"), a.DN("time"), b.DN("time")));
                    row.Add(text);
                }
                lines.Add("| " + cid + " | " + string.Join(" | ", row) + " |");
            }
            lines.Add("");
            lines.Add("| Party | Counted | Mean wins, game | Mean wins, variant | Bosses 15 points easier | Bosses below 50% in the game | of them, 50% or more on the variant | Fights shorter (both won) |");
            lines.Add("|---|---|---|---|---|---|---|---|");
            foreach (var p in parties)
            {
                var rows = summary[p.name];
                var low = rows.Where(r => r.a < lowBelow).ToList();
                var lengths = rows.Where(r => Py.Truthy(r.ta) && Py.Truthy(r.tb)).Select(r => 1 - r.tb.Value / r.ta.Value).ToList();
                lines.Add("| " + p.name + " | " + (p.counted ? "yes" : "no") + " | " + Py.Pct(Py.Sum(rows.Select(r => r.a)) / rows.Count, 0) + " | "
                          + Py.Pct(Py.Sum(rows.Select(r => r.b)) / rows.Count, 0) + " | " + rows.Count(r => r.b - r.a >= flag) + " | " + low.Count + " | "
                          + low.Count(r => r.b >= lowBelow) + " | " + Py.Pct(Py.Sum(lengths) / lengths.Count, 0, true) + " |");
            }
            Func<int, double> se = n => Math.Sqrt(2 * 0.25 / n);
            lines.Add("");
            lines.Add("Two standard errors of a difference of shares near 50%: " + Py.F(2 * se(200) * 100, 0) + " points at 200 battles, " + Py.F(2 * se(100) * 100, 0)
                      + " at 100; less as a share nears 0% or 100%.");
            c.WriteText(c.Path("measures", "WIN_RATES.md"), M.Lines(lines), true);
        }
    }
}
