    /// <summary>measures/boss_rows_check.py: whether each boss the variant made harder still needs it; measures/BOSS_ROWS_CHECK.md.</summary>
    public static class BossRowsCheck
    {
        static List<string> Out(Ctx c, Obj before, Obj after)
        {
            var found = new List<string>();
            foreach (string key in c.In("boss_rows_check").A("keys"))
            {
                double width = c.SetDouble("check_" + key + "_window");
                var a = before.Get(key); var b = after.Get(key);
                if (a == null || b == null) continue;
                if (Math.Abs(Py.Num(b) - Py.Num(a)) > (key == "time" || key == "pressure" ? width * Py.Num(a) : width)) found.Add(key);
            }
            return found;
        }

        static string Fmt(Obj r) => Py.Pct(r.D("won"), 0) + " / " + Py.F(Py.Truthy(r.Get("time")) ? r.D("time") : 0.0, 1) + " / " + Py.Pct(r.D("lowest_hp"), 0);

        public static void Run(Ctx c, int runs = 200)
        {
            var inp = c.In("boss_rows_check");
            var rows = inp.O("rows");
            var known = new HashSet<string>(c.Setup.Checkpoints.Select(r => r.Str("ID")));
            var bosses = rows.Keys.Where(known.Contains).ToList();
            bosses.Sort(string.CompareOrdinal);
            var sides = new[] { ("game", "vanilla"), ("variant", "variant"), ("without", "variant") };
            var jobs = new List<Obj>();
            foreach (var cid in bosses)
                foreach (var (name, side) in sides)
                {
                    var job = new Obj { { "id", cid + "|" + name }, { "measure", "play_checkpoint" }, { "side", side }, { "cid", cid }, { "runs", (long)runs } };
                    if (name == "without" && inp.O("without").Get(cid) is Obj changes && changes.Count > 0) job.Set("enemy_changes", changes);
                    jobs.Add(job);
                }
            var played = c.Measure(jobs);
            var at = new Dictionary<(string, string), Obj>();
            int k = 0;
            foreach (var cid in bosses) foreach (var (name, _) in sides) at[(cid, name)] = M.Summary(played[k++].O("summary"));
            var lines = new List<string>
            {
                "# Whether each boss made harder still needs it (generated by dtcli boss-rows-check)", "",
                "The reference party, " + runs + " battles a cell: wins / length / lowest HP of the party. \"Without its rows\": the variant with the rows of HP, ATK, DEF and INT of that boss taken out. Out of the window: against the game, by the windows of dtcli difficulty-curve.", "",
                "| Boss | Rows | The game | The variant | Out of the window | Without its rows | Out of the window | Reading |", "|---|---|---|---|---|---|---|---|",
            };
            foreach (var cid in bosses)
            {
                var game = at[(cid, "game")]; var modded = at[(cid, "variant")]; var bare = at[(cid, "without")];
                var withRows = Out(c, game, modded); var without = Out(c, game, bare);
                var change = rows.A(cid).Cast<Obj>().Select(r => r.S("Field") + " x" + Py.F(Py.Num(r.Get("New")) / Py.Num(r.Get("Vanilla")), 2)).Distinct().ToList();
                change.Sort(string.CompareOrdinal);
                string reading = without.Count == 0 ? "not needed: within without them" : withRows.Count < without.Count ? "needed" : "no better with them";
                lines.Add("| " + cid + " | " + string.Join("; ", change) + " | " + Fmt(game) + " | " + Fmt(modded) + " | " + (withRows.Count > 0 ? string.Join(", ", withRows) : "within") + " | " + Fmt(bare)
                          + " | " + (without.Count > 0 ? string.Join(", ", without) : "within") + " | " + reading + " |");
            }
            c.WriteText(c.Path("measures", "BOSS_ROWS_CHECK.md"), M.Lines(lines), true);
        }
    }

    /// <summary>The supports and tanks of a stage (measures/support_chains.py and support_stages.py judged()).</summary>
    static class Judged
    {
        public static List<(string stage, List<string> cids, List<(string role, string cls, string kind)> roles)> Plan(Ctx c, Func<string, bool> stageFilter, string control)
        {
            var byClass = c.In("class_kinds");
            var data = c.Data("variant");
            var sc = c.Sc("variant");
            var levels = sc.ReferenceLevels();
            var found = new List<(string, List<string>, List<(string, string, string)>)>();
            foreach (var st in M.Stages(c))
            {
                if (!stageFilter(st.S("Stage"))) continue;
                var cids = ClassStages.Checkpoints(st);
                var roles = new List<(string, string, string)>();
                foreach (var role in c.Setup.RoleOrder)
                {
                    var row = c.Setup.Roles[role];
                    string cls = data.ClassNames[sc.ClassPath(row, levels[cids[cids.Count - 1]].level).cls];
                    string kind = Py.Str(byClass.Get(row.Str("Lv30 class"))) == "support" ? "support" : (byClass.Has(cls) ? Py.Str(byClass.Get(cls)) : "attacker");
                    if (kind == "support" || kind == "tank" || role == control) roles.Add((role, cls, role == control ? "control" : kind));
                }
                found.Add((st.S("Stage"), cids, roles));
            }
            return found;
        }
    }

    /// <summary>measures/support_chains.py: the supports and tanks over a row of random battles; measures/SUPPORT_CHAINS.md.</summary>
    public static class SupportChains
    {
        const string Control = "attacker";

        public static void Run(Ctx c, int chain = 8, int runs = 40)
        {
            var plan = Judged.Plan(c, _ => true, Control);
            var sc = c.Sc("variant");
            var tasks = new List<(string cid, string role)>();
            foreach (var p in plan) foreach (var cid in p.cids) foreach (var r in p.roles) if (!tasks.Contains((cid, r.role))) tasks.Add((cid, r.role));
            var jobs = new List<JobSpec>();
            foreach (var (cid, role) in tasks)
            {
                var cp = c.Checkpoint(cid);
                int level = sc.ReferenceLevels()[cid].level;
                var zones = sc.WalkedZones(cp.Str("Floor"), level);
                var recipe = new Obj { { "drop_last", true }, { "items", "first_kept" }, { "tested", Jb.L(new Obj { { "role", role }, { "forge", sc.ForgeOpen(cp.Str("Floor")) } }) } };
                jobs.Add(Jb.Make(c, "variant", cid, runs: runs, crown: 0, recipe: recipe, options: new Obj { { "random_battle", true } }, name: cid + "|" + role + "|" + chain,
                                 enemies: Jb.Chain(zones.Select(z => z.Name), (int)c.In("support_chains").D("chain_seed"), chain)));
            }
            var done = c.Run(jobs);
            var at = new Dictionary<(string, string), (double won, double hp, double tp)>();
            for (int k = 0; k < tasks.Count; k++)
            {
                var res = done[k].Runs;
                var ok = res.Where(r => r.Won).ToList();
                at[tasks[k]] = ((double)ok.Count / res.Length, ok.Count > 0 ? Py.Sum(ok.Select(r => r.HpLeft)) / ok.Count : 0.0, ok.Count > 0 ? Py.Sum(ok.Select(r => r.TpLeft)) / ok.Count : 0.0);
            }
            var lines = new List<string>
            {
                "# Supports and tanks over a row of random battles (generated by dtcli support-chains)", "",
                "Balance variant. " + chain + " random battles of the floor of each checkpoint in a row, HP and TP carried over, " + runs + " rows a cell, the same rows for every role. Each role in the last place of the reference party. Cells: rows walked to the end / HP the party has left / TP it has left. The last columns: the mean over the checkpoints of the HP and the TP left, as points above the party with an "
                    + Control + " in that place (the control).", "",
            };
            foreach (var (stage, cids, roles) in plan)
            {
                lines.Add("## " + stage + " (" + string.Join(", ", cids) + ")");
                lines.Add("");
                lines.Add("| Role | Class | Kind | " + string.Join(" | ", cids) + " | HP left against the control | TP left against the control |");
                lines.Add("|" + string.Concat(Enumerable.Repeat("---|", 5 + cids.Count)));
                foreach (var (role, cls, kind) in roles)
                {
                    string cells = string.Join(" | ", cids.Select(x => { var m = at[(x, role)]; return Py.Pct(m.won, 0) + " / " + Py.Pct(m.hp, 0) + " / " + Py.Pct(m.tp, 0); }));
                    double hp = Py.Mean(cids.Select(x => at[(x, role)].hp - at[(x, Control)].hp));
                    double tp = Py.Mean(cids.Select(x => at[(x, role)].tp - at[(x, Control)].tp));
                    lines.Add("| " + role + " | " + cls + " | " + kind + " | " + cells + " | " + Py.F(hp * 100, 0, true) + " | " + Py.F(tp * 100, 0, true) + " |");
                }
                lines.Add("");
            }
            c.WriteText(c.Path("measures", "SUPPORT_CHAINS.md"), M.Lines(lines), true);
        }
    }

    /// <summary>measures/support_stages.py: the supports and tanks where every fight is won; measures/SUPPORT_STAGES.md.</summary>
    public static class SupportStages
    {
        public static void Run(Ctx c, int runs = 60)
        {
            var plan = Judged.Plan(c, s => s == "base" || s == "intermediate", null);
            var tasks = new List<(string cid, string role)>();
            foreach (var p in plan) foreach (var cid in p.cids) foreach (var r in p.roles) if (!tasks.Contains((cid, r.role))) tasks.Add((cid, r.role));
            var done = c.Run(tasks.Select(t => ClassStages.Job(c, t.cid, t.role, runs)).ToList());
            var sc = c.Sc("variant");
            var at = new Dictionary<(string, string), Obj>();
            for (int k = 0; k < tasks.Count; k++)
                at[tasks[k]] = ClassStages.Figures(done[k].Runs, runs, done[k].Spec.TestedNames.Count > 0 ? done[k].Spec.TestedNames[0] : null, sc.ReferenceLevels()[tasks[k].cid].level, tasks[k].role);
            var lines = new List<string>
            {
                "# Supports and tanks where every fight is won (generated by dtcli support-stages)", "",
                "Balance variant, " + runs + " battles a cell. Each role in the last place of the reference party. Cells: the lowest share of HP the party fell to during the fight / the share it ended with / the length of the fight. The last columns are the mean over the checkpoints of the difference from the median role of the table: points of lowest HP (more is safer) and length (less is faster).", "",
            };
            foreach (var (stage, cids, roles) in plan)
            {
                lines.Add("## " + stage + " (" + string.Join(", ", cids) + ")");
                lines.Add("");
                lines.Add("| Role | Class | Kind | " + string.Join(" | ", cids) + " | Wins | Lowest HP against the median | Length against the median |");
                lines.Add("|" + string.Concat(Enumerable.Repeat("---|", 6 + cids.Count)));
                var low = cids.ToDictionary(x => x, x => Py.Median(roles.Select(r => at[(x, r.role)].D("lowest_hp"))));
                var time = cids.ToDictionary(x => x, x => Py.Median(roles.Select(r => at[(x, r.role)].D("time"))));
                foreach (var (role, cls, kind) in roles)
                {
                    var mine = cids.Select(x => at[(x, role)]).ToList();
                    string cells = string.Join(" | ", mine.Select(m => Py.Pct(m.D("lowest_hp"), 0) + " / " + Py.Pct(m.D("hp_left"), 0) + " / " + Py.F(m.D("time"), 1)));
                    double gap = Py.Sum(cids.Select(x => at[(x, role)].D("lowest_hp") - low[x])) / cids.Count;
                    double ratio = Py.Sum(cids.Select(x => at[(x, role)].D("time") / time[x])) / cids.Count;
                    double wins = mine.Min(m => m.D("won"));
                    lines.Add("| " + role + " | " + cls + " | " + kind + " | " + cells + " | " + Py.Pct(wins, 0) + " | " + Py.F(gap * 100, 0, true) + " | " + Py.F(ratio, 2) + " |");
                }
                lines.Add("");
            }
            c.WriteText(c.Path("measures", "SUPPORT_STAGES.md"), M.Lines(lines), true);
        }
    }
