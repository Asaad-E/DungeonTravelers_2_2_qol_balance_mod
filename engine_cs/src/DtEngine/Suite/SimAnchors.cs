using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

namespace DtEngine.Suite
{
    /// <summary>tools/sim_anchors.py: the boss fights whose level the guides state, played by the reference party; docs/generated/SIM_ANCHORS.md.</summary>
    public static class SimAnchors
    {
        public static void Run(Ctx c)
        {
            int runs = c.SetInt("anchor_runs");
            var rows = M.Rows(c, "anchors");
            var plan = new List<(int level, List<int> numbers)>();
            var jobs = new List<JobSpec>();
            foreach (var row in rows)
            {
                string cid = Py.Str(row.Get("Checkpoint"));
                var cp = c.Checkpoint(cid);
                var lv = row.Get("Level (blank: reference level)");
                int level = lv != null ? (int)Py.Num(lv) : c.Sc("vanilla").ReferenceLevels()[cid].level;
                var battles = row.Get("Battles (blank: those of the checkpoint)");
                var numbers = Py.Truthy(battles) ? Py.Str(battles).Split('+').Select(n => int.Parse(n.Trim())).ToList() : Scenario.BattleNumbers(cp).ToList();
                plan.Add((level, numbers));
                jobs.Add(Jb.Make(c, "vanilla", cid, runs: runs, level: level, enemies: Jb.Fixed(cp.Str("Floor"), numbers)));
            }
            var played = c.Run(jobs);
            var lines = new List<string>();
            var limits = new List<string>();
            int met = 0;
            for (int k = 0; k < rows.Count; k++)
            {
                var row = rows[k];
                double share = (double)played[k].Runs.Count(r => r.Won) / runs;
                var low = row.Get("Lowest win share"); var high = row.Get("Highest win share");
                bool ok = (low == null || share >= Setup.ToDouble(low)) && (high == null || share <= Setup.ToDouble(high));
                if (ok) met++;
                if (!ok && Py.Truthy(row.Get("Known limit"))) limits.Add("- **" + Py.Str(row.Get("ID")) + "**: " + Py.Str(row.Get("Known limit")));
                string bounds = (low == null ? "" : Py.Pct(Setup.ToDouble(low), 0)) + " - " + (high == null ? "" : Py.Pct(Setup.ToDouble(high), 0));
                lines.Add("| " + Py.Str(row.Get("ID")) + " | " + Py.Str(row.Get("Checkpoint")) + " | " + string.Join("+", plan[k].numbers) + " | " + plan[k].level + " | "
                          + Py.Pct(share, 0) + " | " + bounds + " | " + (ok ? "yes" : "no") + " | " + Py.Str(row.Get("What the source says, read as a win share")) + " ("
                          + Py.Str(row.Get("Source")) + ") |");
            }
            var outLines = new List<string>
            {
                "# Anchors of the simulator (generated)", "",
                "Generated by `dtcli sim-anchors` from the sheet `Anchors` of `data_tables/sim_setup.xlsx`. Do not edit: run the tool again.", "",
                "Anchors met: **" + met + " of " + rows.Count + "**, " + runs + " battles each, with the settings of the workbook (kit_count " + Py.Str(c.Setup.Settings.GetValueOrDefault("kit_count"))
                    + "). Known limits (not met, declared in the column `Known limit`): **" + limits.Count + "**.", "",
                "| ID | Checkpoint | Battles | Level | Won | Expected | Met | Source |", "|---|---|---|---|---|---|---|---|",
            };
            outLines.AddRange(lines);
            if (limits.Count > 0) { outLines.Add(""); outLines.Add("## Known limits"); outLines.Add(""); outLines.AddRange(limits); }
            c.WriteText(c.Path("docs", "generated", "SIM_ANCHORS.md"), M.Lines(outLines), false);
        }
    }
}
