    /// <summary>measures/postgame_compare.py: the postgame on the variant against vanilla, boss by boss, at the preparation each fight asks for;
    /// measures/POSTGAME_COMPARE.md.</summary>
    public static class PostgameCompare
    {
        public static Obj SummaryOf(JobResult done)
        {
            var s = Summary.Of(done.Runs.ToList());
            return new Obj { { "won", s.Won }, { "time", s.Time.HasValue ? (object)s.Time.Value : null }, { "lowest_hp", s.LowestHp }, { "pressure", s.Pressure } };
        }

        public static void Run(Ctx c)
        {
            int runs = c.SetInt("check_runs");
            var steps = c.In("postgame_compare").A("steps").Select(x => (int)Py.Num(x)).ToList();
            var rows = M.Rows(c, "guide_sheet").Where(r => Py.Str(r.Get("Checkpoint")).StartsWith("P")).ToList();
            // the least crown bonus at which the vanilla party reaches the floor of the class of the boss: one step for every boss at a time
            var state = rows.Select(r =>
            {
                string cid = Py.Str(r.Get("Checkpoint"));
                var cp = c.Checkpoint(cid);
                int first = cp.Truthy("Crown bonus") ? cp.Int("Crown bonus") : 0;
                return new
                {
                    Row = r, Cid = cid, Floor = Setup.ToDouble(c.Setup.Settings["guide_" + Py.Str(r.Get("Class")) + "_min_won"]),
                    Steps = steps.Where(s => s >= first).ToList(), Vanilla = (Obj)null, Crown = 0, At = 0, Done = false,
                };
            }).ToList();
            var steps2 = state.Select(s => s.Steps).ToList();
            var at = new int[rows.Count]; var done = new bool[rows.Count]; var vanilla = new Obj[rows.Count]; var crown = new int?[rows.Count];
            while (true)
            {
                var active = Enumerable.Range(0, rows.Count).Where(i => !done[i] && at[i] < steps2[i].Count).ToList();
                if (active.Count == 0) break;
                var jobs = active.Select(i => Jb.Make(c, "vanilla", state[i].Cid, runs: runs, crown: steps2[i][at[i]], name: state[i].Cid + "|" + steps2[i][at[i]])).ToList();
                var played = c.Run(jobs);
                for (int k = 0; k < active.Count; k++)
                {
                    int i = active[k];
                    vanilla[i] = SummaryOf(played[k]); crown[i] = steps2[i][at[i]];
                    if (vanilla[i].D("won") >= state[i].Floor) done[i] = true; else at[i]++;
                }
            }
            var variantJobs = Enumerable.Range(0, rows.Count).Select(i => Jb.Make(c, "variant", state[i].Cid, runs: runs, crown: crown[i], name: state[i].Cid + "|" + crown[i])).ToList();
            var variantDone = c.Run(variantJobs);
            var outRows = new List<object>();
            for (int i = 0; i < rows.Count; i++)
                outRows.Add(new Obj
                {
                    { "id", state[i].Cid }, { "boss", rows[i].Get("Boss") }, { "class", rows[i].Get("Class") }, { "floor", state[i].Floor }, { "crown", (long)crown[i].Value },
                    { "vanilla", vanilla[i] }, { "variant", SummaryOf(variantDone[i]) },
                });
            Parts.Write(c, "postgame_compare", outRows);
        }

        static string Length(Obj x) => Py.Truthy(x.Get("time")) ? Py.F(x.D("time"), 1) : "-";

        public static void Report(Ctx c)
        {
            var rows = Parts.Read(c, "postgame_compare").OrderBy(r => r.S("id"), StringComparer.Ordinal).ToList();
            var reached = rows.Where(r => r.O("vanilla").D("won") >= r.D("floor")).ToList();
            var easier = reached.Where(r => r.O("variant").D("won") - r.O("vanilla").D("won") > 0.15).ToList();
            var harder = reached.Where(r => r.O("vanilla").D("won") - r.O("variant").D("won") > 0.15).ToList();
            var lines = new List<string>
            {
                "# The postgame on the variant against vanilla (generated by measures/postgame_compare.py)", "",
                "**" + rows.Count + " bosses; vanilla reaches the floor of its class at " + reached.Count + " of them within a crown bonus of 50; of those, the variant wins over 15 points more at "
                    + easier.Count + " and over 15 points less at " + harder.Count + ".**", "",
                "Crown: the least bonus at which the vanilla party reaches the floor (the preparation the fight asks for in the model; 50 where it never does).", "",
                "| Boss | Class | Crown | Wins, vanilla > variant | Length, vanilla > variant | Lowest HP |", "|---|---|---|---|---|---|",
            };
            foreach (var r in rows)
            {
                var v = r.O("vanilla"); var m = r.O("variant");
                string mark = reached.Contains(r) ? "" : " (floor not reached)";
                lines.Add("| " + r.S("id") + " " + Py.Str(r.Get("boss")) + " | " + Py.Str(r.Get("class")) + " | " + r.L("crown") + mark + " | " + Py.Pct(v.D("won"), 0) + " > " + Py.Pct(m.D("won"), 0) + " | "
                          + Length(v) + " > " + Length(m) + " | " + Py.Pct(v.D("lowest_hp"), 0) + " > " + Py.Pct(m.D("lowest_hp"), 0) + " |");
            }
            c.WriteText(c.Path("measures", "POSTGAME_COMPARE.md"), M.Lines(lines), true);
        }
    }

    /// <summary>measures/unique_skills.py: what the unique skill of each girl adds; measures/UNIQUE_SKILLS.md.</summary>
    public static class UniqueSkills
    {
        public static void Run(Ctx c, int runs = 60)
        {
            var inp = c.In("unique_skills");
            var roles = inp.O("roles");
            var places = inp.A("places").Cast<List<object>>().Select(p => ((string)p[0], (int)Py.Num(p[1]))).ToList();
            var pep = inp.O("pep");
            var data = c.Data("variant");
            var girls = roles.Keys.ToList(); girls.Sort(string.CompareOrdinal);
            var jobs = new List<JobSpec>();
            foreach (var girl in girls)
                foreach (var (cid, crown) in places)
                    foreach (var withSkill in new[] { false, true })
                    {
                        var cp = c.Checkpoint(cid);
                        var tested = new Obj { { "role", roles.Get(girl) }, { "character", girl }, { "no_unique", !withSkill }, { "forge", c.Sc("variant").ForgeOpen(cp.Str("Floor")) }, { "unique_pieces", true } };
                        if (pep.Has(girl)) tested.Set("pep", pep.Get(girl));
                        var recipe = new Obj { { "name_not", girl }, { "first", 4L }, { "items", "first_kept" }, { "tested", Jb.L(tested) } };
                        jobs.Add(Jb.Make(c, "variant", cid, runs: runs, crown: crown, recipe: recipe, name: girl + "|" + cid + "|" + crown + "|" + (withSkill ? 1 : 0)));
                    }
            var done = c.Run(jobs);
            var rows = new List<object>();
            int at = 0;
            foreach (var girl in girls)
            {
                var character = data.Characters.First(x => x.Name == girl);
                var unique = inp.O("skills").O(character.UniqueSkill.ToString());
                var cells = new List<object>();
                foreach (var (cid, crown) in places)
                {
                    var a = Parts.Cell(done[at++]); var b = Parts.Cell(done[at++]);
                    cells.Add(new Obj { { "checkpoint", cid }, { "crown", (long)crown }, { "without", a }, { "with", b } });
                }
                rows.Add(new Obj { { "girl", girl }, { "role", roles.Get(girl) }, { "skill", unique.Get("name") }, { "values", unique.Get("values") }, { "cells", cells } });
            }
            Parts.Write(c, "unique_skills", rows);
        }

        public static void Report(Ctx c)
        {
            var places = c.In("unique_skills").A("places").Cast<List<object>>().Select(p => ((string)p[0], (int)Py.Num(p[1]))).ToList();
            var rows = Parts.Read(c, "unique_skills");
            var scored = new List<(double wins, Obj row, List<string> cells, double length, double hp)>();
            Func<List<double>, double> mean = xs => xs.Count > 0 ? Py.Sum(xs) / xs.Count : 0.0;
            foreach (var r in rows)
            {
                var cells = new List<string>(); var wins = new List<double>(); var lengths = new List<double>(); var hps = new List<double>();
                foreach (Obj cell in r.A("cells"))
                {
                    var a = cell.O("without"); var b = cell.O("with");
                    wins.Add(b.D("won") - a.D("won"));
                    hps.Add(b.D("hp_left") - a.D("hp_left"));
                    double? length = Py.Truthy(a.Get("time")) && Py.Truthy(b.Get("time")) ? 1 - b.D("time") / a.D("time") : (double?)null;
                    if (length != null) lengths.Add(length.Value);
                    cells.Add(Py.Pct(a.D("won"), 0) + " > " + Py.Pct(b.D("won"), 0) + (length != null ? " (" + Py.Pct(length.Value, 0, true) + ")" : ""));
                }
                scored.Add((mean(wins), r, cells, mean(lengths), mean(hps)));
            }
            var ordered = scored.OrderBy(s => -(s.wins + s.length)).ToList();
            string head = string.Join(" | ", places.Select(p => p.Item1 + (p.Item2 != 0 ? " crowned" : "")));
            var lines = new List<string>
            {
                "# What each unique skill adds (generated by measures/unique_skills.py)", "",
                "The reference party with the girl in its last place, without her unique skill > with it: wins, and in brackets how much shorter the won fights are with it. Variant; sorted by the mean of wins and length gained.", "",
                "| Girl | Unique skill | Role | " + head + " | Wins, mean | Length, mean | HP left, mean |", "|---|---|---|" + string.Concat(Enumerable.Repeat("---|", places.Count + 3)),
            };
            foreach (var (wins, r, cells, length, hp) in ordered)
                lines.Add("| " + r.S("girl") + " | " + Py.Str(r.Get("skill")) + " | " + r.S("role") + " | " + string.Join(" | ", cells) + " | " + Py.F(wins * 100, 0, true) + " | " + Py.Pct(length, 0, true) + " | " + Py.F(hp * 100, 0, true) + " |");
            c.WriteText(c.Path("measures", "UNIQUE_SKILLS.md"), M.Lines(lines), true);
        }
    }
