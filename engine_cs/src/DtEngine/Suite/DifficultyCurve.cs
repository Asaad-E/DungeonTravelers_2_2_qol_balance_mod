using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

namespace DtEngine.Suite
{
    /// <summary>tools/difficulty_curve.py: the variant against vanilla at every boss checkpoint; docs/generated/DIFFICULTY_CURVE.md.</summary>
    public static class DifficultyCurve
    {
        static readonly string[] Figures = { "won", "time", "lowest_hp", "pressure" };
        static double Easier(string key) => key == "time" || key == "pressure" ? -1 : 1;     // the sign of a change that makes a fight easier

        public static List<string> Checkpoints(Ctx c)
        {
            var found = c.Setup.Checkpoints.Select(r => r.Str("ID")).Where(id => id.StartsWith("C")).ToList();
            var late = M.Stages(c).FirstOrDefault(s => s.S("Stage") == "late");
            if (late != null) found.AddRange(late.Get("Checkpoints").ToString().Split(';').Select(x => x.Trim()));
            return found;
        }

        public static void Run(Ctx c)
        {
            string dir = c.Path("docs", "generated", "difficulty_curve");
            var jobs = Checkpoints(c).Select(cid => new Obj
            {
                { "id", "cc-" + cid }, { "measure", "check_change" }, { "side", "vanilla" }, { "changed_side", "variant" },
                { "checkpoints", Jb.L(cid) }, { "runs", null },
            }).ToList();
            var rows = new List<object>();
            foreach (var raw in c.Measure(jobs))
                foreach (Obj row in raw.A("rows"))
                {
                    var before = M.Summary(row.O("before")); before.Set("level", row.L("level_before"));
                    var after = M.Summary(row.O("after")); after.Set("level", row.L("level_after"));
                    rows.Add(new Obj { { "id", row.S("cid") }, { "vanilla", before }, { "variant", after }, { "out", row.A("out") } });
                }
            Directory.CreateDirectory(dir);
            M.ClearFolder(dir);
            c.WriteText(Path.Combine(dir, "part_1.json"), PyJson.Dump(rows), false);
        }

        public static string Fmt(object v, string key)
        {
            if (v == null) return "-";
            double x = Py.Num(v);
            return key == "won" || key == "lowest_hp" ? Py.Pct(x, 0) : key == "pressure" ? Py.F(x, 2) : Py.F(x, 1);
        }

        public static void Report(Ctx c)
        {
            string dir = c.Path("docs", "generated", "difficulty_curve");
            var rows = new List<Obj>();
            foreach (var name in M.Listing(dir)) rows.AddRange(((List<object>)c.ReadJson(Path.Combine(dir, name))).Cast<Obj>());
            var order = Checkpoints(c);
            rows = rows.OrderBy(r => order.IndexOf(r.S("id"))).ToList();
            int easier = 0, harder = 0;
            var lines = new List<string>();
            foreach (var r in rows)
            {
                var signs = new List<string>();
                var vanilla = r.O("vanilla"); var variant = r.O("variant");
                foreach (string key in r.A("out"))
                {
                    var a = vanilla.Get(key); var b = variant.Get(key);
                    if (a == null || b == null) { signs.Add(b == null ? key + " lost" : key + " new"); continue; }
                    signs.Add(key + " " + ((Py.Num(b) - Py.Num(a)) * Easier(key) > 0 ? "easier" : "harder"));
                }
                bool easy = signs.Any(s => s.EndsWith("easier")), hard = signs.Any(s => s.EndsWith("harder"));
                if (easy) easier++;
                if (hard && !easy) harder++;
                string cells = string.Join(" | ", Figures.Select(k => Fmt(vanilla.Get(k), k) + " > " + Fmt(variant.Get(k), k)));
                lines.Add("| " + r.S("id") + " | " + Py.Str(vanilla.Get("level")) + " | " + cells + " | " + (signs.Count > 0 ? string.Join(", ", signs) : "within") + " |");
            }
            var text = new List<string>
            {
                "# Difficulty of the variant against vanilla (generated)", "",
                "Generated by `tools/difficulty_curve.py`. Do not edit. The reference party at the reference level of each checkpoint, vanilla > Balance variant. Windows: Settings check_*_window.", "",
                "**" + (rows.Count - easier - harder) + " of " + rows.Count + " checkpoints within the windows of vanilla; " + easier + " easier, " + harder + " harder.**", "",
                "| Checkpoint | Level | Wins | Length | Lowest HP | Pressure | Out of the window |",
                "|---|---|---|---|---|---|---|",
            };
            text.AddRange(lines);
            c.WriteText(c.Path("docs", "generated", "DIFFICULTY_CURVE.md"), M.Lines(text), false);
        }
    }
}
