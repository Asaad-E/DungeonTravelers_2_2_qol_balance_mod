using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

namespace DtEngine.Suite
{
    /// <summary>tools/guide_curve.py: the story bosses against what the guide says of them; docs/generated/GUIDE_CURVE.md.</summary>
    public static class GuideCurve
    {
        public static void Run(Ctx c)
        {
            string dir = c.Path("docs", "generated", "guide_curve");
            var rows = M.Rows(c, "guide_sheet");
            int runs = c.SetInt("check_runs");
            var jobs = new List<Obj>();
            for (int k = 0; k < rows.Count; k++)
                jobs.Add(new Obj { { "id", "pc" + k }, { "measure", "play_checkpoint" }, { "side", "vanilla" }, { "cid", Py.Str(rows[k].Get("Checkpoint")) }, { "runs", (long)runs } });
            var played = c.Measure(jobs);
            var outRows = new List<object>();
            for (int k = 0; k < rows.Count; k++)
            {
                var summary = M.Summary(played[k].O("summary"));
                outRows.Add(new Obj { { "id", rows[k].Get("Checkpoint") }, { "level", played[k].L("level") }, { "won", summary.D("won") },
                                      { "time", summary.Get("time") }, { "lowest_hp", summary.D("lowest_hp") } });
            }
            Directory.CreateDirectory(dir);
            M.ClearFolder(dir);
            c.WriteText(Path.Combine(dir, "part_1.json"), PyJson.Dump(outRows, 1), false);
        }

        public static void Report(Ctx c)
        {
            string dir = c.Path("docs", "generated", "guide_curve");
            var rows = M.Rows(c, "guide_sheet");
            var measured = new Dictionary<string, Obj>();
            foreach (var name in M.Listing(dir))
                foreach (Obj m in (List<object>)c.ReadJson(Path.Combine(dir, name))) measured[m.S("id")] = m;
            var readings = new Dictionary<string, Obj>();
            foreach (var r in M.Rows(c, "audit_readings")) readings[Py.Str(r.Get("ID")).Trim()] = r;
            var lines = new List<string>();
            int inside = 0, read = 0;
            var missing = new List<string>();
            foreach (var r in rows)
            {
                string cid = Py.Str(r.Get("Checkpoint"));
                measured.TryGetValue(cid, out var m);
                double floor = Setup.ToDouble(c.Setup.Settings["guide_" + Py.Str(r.Get("Class")) + "_min_won"]);
                if (m == null) { missing.Add(cid); continue; }
                bool ok = m.D("won") >= floor;
                readings.TryGetValue("curve " + cid, out var reading);
                if (ok) inside++;
                if (!ok && reading != null) read++;
                string state = ok ? "within" : reading != null ? "read: " + Py.Str(reading.Get("Result")) : "**below, unread**";
                lines.Add("| " + cid + " | " + Py.Str(r.Get("Boss")) + " | " + Py.Str(r.Get("Class")) + " | " + Py.Str(m.Get("level")) + " | " + Py.Pct(m.D("won"), 0) + " | "
                          + Py.Pct(floor, 0) + " | " + state + " |");
            }
            int total = rows.Count;
            var text = new List<string>
            {
                "# The story bosses against the guide (generated)", "",
                "Generated by `dtcli guide-curve`. Do not edit: run the slices again, then `report`.", "",
                "**Checklist: " + inside + " of " + total + " bosses within the floor of their class, " + read + " below and read, " + (total - inside - read - missing.Count)
                    + " below and unread, " + missing.Count + " not measured.**", "",
                "Vanilla data; the reference party at the reference level of each checkpoint. Class: what the GameFAQs guide says of the boss (sheet GuideDifficulty). Floor: the least win share that class allows.", "",
                "| Checkpoint | Boss | Class | Level | Won | Floor | State |", "|---|---|---|---|---|---|---|",
            };
            text.AddRange(lines);
            c.WriteText(c.Path("docs", "generated", "GUIDE_CURVE.md"), M.Lines(text), false);
        }
    }
}
