"""How well each postgame boss fight is modelled: for every checkpoint of the postgame, its enemies, the effects of
their attacks and passives the simulator does not act on, the parts of their scripts it does not run, the zone of the
cell, and what the guide curve measured. Read only; writes scratch/audit_2026-10-11/POSTGAME_AUDIT.md.

    python postgame_audit.py
"""
import collections
import os
import re
import sys

import openpyxl

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, PROJECT)
sys.path.insert(0, os.path.join(PROJECT, 'tools'))
import enemy_ai                                                  # noqa: E402
import sim_coverage                                              # noqa: E402
from sim import battle as battle_mod, scenario, setup as setup_mod   # noqa: E402
from sim.data import game_data                                   # noqa: E402

OUTPUT = os.path.join(HERE, 'POSTGAME_AUDIT.md')


def effect_names():
    path = os.path.join(PROJECT, 'data_tables', 'vanilla_source_of_truth.xlsx')
    rows = openpyxl.load_workbook(path, read_only=True)['Effects'].iter_rows(values_only=True)
    head = next(rows)
    return {r[0]: str(r[1]) for r in rows if r and r[0] is not None}


def guide_curve():
    found = {}
    path = os.path.join(PROJECT, 'docs', 'generated', 'GUIDE_CURVE.md')
    for line in open(path, encoding='utf-8'):
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        if len(cells) >= 7 and re.fullmatch(r'[CP]\d+\w?', cells[0]):
            found[cells[0]] = cells
    return found


def main():
    data, setup = game_data(), setup_mod.load()
    names = effect_names()
    handled = set(battle_mod.HANDLED) | set(battle_mod.ASSUMED)
    commands, sources, targets = sim_coverage.ai_parts()
    gaps = collections.defaultdict(list)
    for eid, _, what in sim_coverage.script_gaps(data, commands, sources, targets):
        gaps[eid].append(what)
    curve = guide_curve()
    postgame = {r['ID']: r for r in setup_mod._rows(openpyxl.load_workbook(setup_mod.SETUP, read_only=True), 'PostgameBosses')}
    lines = ['# Postgame bosses: how each fight is modelled (generated by scratch/audit_2026-10-11/postgame_audit.py)', '']
    table, missing_total, tally = [], collections.Counter(), collections.Counter()
    for cp in setup.checkpoints:
        cid = cp['ID']
        if not cid.startswith('P'):
            continue
        row = postgame.get(cid, {})
        problems, parts = [], []
        for number in scenario.battle_numbers(cp):
            try:
                fight = next(b for b in data.fixed if b['floor'] == cp['Floor'] and b['number'] == number)
            except StopIteration:
                problems.append(f'battle {number} of {cp["Floor"]} is not in the data')
                continue
            zone = scenario.battle_zone(data, cp['Floor'], number)
            if zone is None:
                problems.append(f'battle {number}: no cell found, the zone of the fight is unknown')
            elif zone.get('no_magic') or zone.get('slots'):
                parts.append(f"zone slots {zone['slots']}{', no magic' if zone.get('no_magic') else ''}")
            for eid, _ in fight['enemies']:
                enemy = data.enemies[eid]
                unhandled = collections.defaultdict(list)
                for aid in list(enemy['attacks']) + list(enemy['passives']):
                    attack = data.attacks.get(aid)
                    if attack is None:
                        problems.append(f"{enemy['name']}: attack {aid} is not in the data")
                        continue
                    for effect, _, _ in attack.effects:
                        if effect not in handled:
                            unhandled[effect].append(attack.name)
                for effect, where in sorted(unhandled.items()):
                    problems.append(f"{enemy['name']}: effect {effect} ({names.get(effect, '?')}) of "
                                    f"{', '.join(sorted(set(where)))} is not acted on")
                    missing_total[(effect, names.get(effect, '?'))] += 1
                for what in gaps.get(eid, ()):
                    problems.append(f"{enemy['name']}: script, {what}")
                if enemy['script'] is None and not enemy['ai']:
                    problems.append(f"{enemy['name']}: no script")
                parts.append(f"{enemy['name']} L{enemy['level']} {enemy['hp']:,} HP")
        measured = curve.get(cid)
        verdict = measured[-1] if measured else 'not in the guide curve'
        tally['modelled in full' if not problems else 'with gaps'] += 1
        table.append((cid, row.get('Boss') or cp.get('Boss (as the story page names it)'), '; '.join(parts),
                      measured[2] if measured else '-', measured[4] if measured else '-', verdict,
                      '<br>'.join(problems) or '-', row.get('What the guide says') or '-'))
    lines += [f"**{tally['modelled in full']} of {len(table)} fights hold nothing the simulator does not act on; "
              f"{tally['with gaps']} hold something.**", '',
              '## What is missing, by effect', '', '| Effect | Name | Enemies of the postgame that use it |', '|---|---|---|']
    lines += [f'| {e} | {n} | {c} |' for (e, n), c in missing_total.most_common()]
    lines += ['', '## Fight by fight', '',
              '| ID | Boss | Enemies and zone | Class | Reference party wins | Guide curve | Not modelled | The guide |',
              '|---|---|---|---|---|---|---|---|']
    lines += ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in table]
    with open(OUTPUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(lines[2])
    for (e, n), c in missing_total.most_common():
        print(f'  effect {e} ({n}): {c}')
    for r in table:
        print(f'{r[0]} | {str(r[1])[:38]} | {r[3]} | {r[4]} | {r[5]} | {str(r[6])[:150]}')


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    main()
